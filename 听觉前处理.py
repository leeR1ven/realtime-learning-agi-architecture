import numpy as np

class 特征神经元池:
    """numpy 版：所有神经元共用两个数组，速度比对象版快几十到几百倍"""

    def __init__(self, 对数):
        self.对数 = 对数
        self.总数 = 对数 * 2
        self.信号 = np.zeros(self.总数)              # 每个神经元的信号
        self.激活 = np.zeros(self.总数, dtype=bool)  # 每个神经元是否激活

    def 接收信号(self, 编号, 值):
        self.信号[编号] += 值

    def 更新所有对(self):
        正信号 = self.信号[0::2]   # 偶数下标 = 正神经元
        反信号 = self.信号[1::2]   # 奇数下标 = 反神经元
        正赢 = 正信号 >= 反信号    # 平局时正神经元赢
        self.激活[0::2] = 正赢
        self.激活[1::2] = ~正赢
        self.信号[:] = 0.0         # 清空本轮信号


class 神经网络:
    """局部连接版：每个神经元只连上一层附近的神经元（首尾成环）"""

    def __init__(self, 输入层, 层数, 连接半径=10,
                 权重范围=0.1, 阈值初值=0.5):
        self.输入层 = 输入层
        self.对数 = 输入层.对数
        self.层数 = 层数
        self.半径 = 连接半径
        self.每层数 = 输入层.总数
        self.输出层数量 = self.每层数  # 最后一层神经元数量（记忆区靠它同步）
        连接数 = 2 * 连接半径 + 1   # 每个神经元连几个邻居

        self.来源 = []
        self.权重 = []
        self.阈值 = [np.full(self.每层数, 阈值初值) for _ in range(层数 - 1)]
        self.普通层激活 = [np.zeros(self.每层数, dtype=bool) for _ in range(层数 - 1)]

        for _ in range(层数 - 1):
            # 目标神经元 j 连上一层 j-半径 ~ j+半径，取模使首尾相接成环
            偏移 = np.arange(-连接半径, 连接半径 + 1)
            目标 = np.arange(self.每层数)
            来源 = (目标[:, None] + 偏移[None, :]) % self.每层数
            权重 = np.random.uniform(0, 权重范围, size=(self.每层数, 连接数))
            self.来源.append(来源)
            self.权重.append(权重)

    def 前向传播(self, 输入信号):
        self.输入层.信号[:] = 输入信号
        self.输入层.更新所有对()
        当前激活 = self.输入层.激活.astype(float)

        for k in range(self.层数 - 1):
            加权和 = (self.权重[k] * 当前激活[self.来源[k]]).sum(axis=1)
            当前激活 = 加权和 >= self.阈值[k]   # 神经元自己的放电门槛
            self.普通层激活[k] = 当前激活
            当前激活 = 当前激活.astype(float)

        return 当前激活


# ============================================================
# 听觉输入布局：想改频带数 / 响度档数，只改下面这一块数字
# ============================================================
声道数 = 1          # 1 = 单声道；2 = 左右声道（以后做立体声时改成 2）
频带数 = 1500       # 频率分成多少根带（喂进来的频谱会压缩成这么多根）
每档对数 = 10       # 每根频带用几对神经元 = 几档响度（10 对 = 0~10 共 11 级）
层数 = 3
连接半径 = 10
权重范围 = 0.1
阈值初值 = 0.6

对数 = 声道数 * 频带数 * 每档对数       # 输入层特征神经元对数
池 = 特征神经元池(对数)
网 = 神经网络(池, 层数=层数, 连接半径=连接半径,
             权重范围=权重范围, 阈值初值=阈值初值)


def 压缩频谱(频谱):
    """任意长度的幅度谱 -> (声道数, 频带数)，每根带取块平均。

    输入：
      单声道：1D 数组（长度任意，>= 频带数）；
      多声道：2D (声道数, 长度)，长度 >= 频带数。
    数值约定 0~1（喂进来之前可自己先做响度压缩，例如取对数谱/梅尔谱）。
    """
    谱 = np.asarray(频谱, dtype=np.float64)
    if 谱.ndim == 1:
        if 声道数 != 1:
            raise ValueError("多声道时请给 (声道数, 频点数) 的二维频谱")
        谱 = 谱[None, :]
    if 谱.ndim != 2 or 谱.shape[0] != 声道数:
        raise ValueError("频谱形状应为 (声道数, 频点数)")
    L = 谱.shape[1]
    if L < 频带数:
        raise ValueError("频点数少于频带数，请先提高频谱分辨率")
    xs = (np.arange(频带数 + 1) * L) // 频带数
    和 = np.add.reduceat(谱, xs[:-1], axis=1)
    宽 = (xs[1:] - xs[:-1])[None, :]
    return 和 / 宽


def 频谱转信号(频谱):
    """幅度谱 -> 池.信号（温度计码：响度 L 档 = 该频带前 L 对正激活）

    响度 0   = 该频带全部反神经元激活（没声音）；
    响度满   = 该频带全部正神经元激活（最响）；
    中间响度 = 前 L 对正激活、后 k-L 对反激活（交界位置 = 响度值）。
    """
    缩 = np.clip(压缩频谱(频谱), 0.0, 1.0)
    级 = np.clip(np.rint(缩 * 每档对数).astype(int), 0, 每档对数)

    信号 = np.zeros(池.总数)
    cc = np.arange(声道数)[:, None, None]
    bb = np.arange(频带数)[None, :, None]
    起点 = (cc * 频带数 + bb) * 每档对数      # 每个(声道,频带)的对起点
    for j in range(每档对数):
        对 = 起点 + j
        正掩码 = 级 > j                    # 响度超过第 j 档 -> 这一对正激活
        信号[(2 * 对)[正掩码]] = 1.0
        信号[(2 * 对 + 1)[~正掩码]] = 1.0
    return 信号


def 解码响度(激活=None):
    """从输入层激活读回每根频带的响度（0~每档对数），用来检查编码"""
    if 激活 is None:
        激活 = 池.激活
    正 = 激活[0::2]                       # 每对的正神经元是否激活
    return 正.reshape(声道数, 频带数, 每档对数).sum(axis=2)


def 造测试频谱(模式, 帧=0, 长度=4096):
    """合成测试频谱（0~1 幅度，模拟一次短时频谱，长度任意 >= 频带数）"""
    f = np.arange(长度)
    if 模式 == "扫频":
        # 一个高斯峰，每帧往高频方向移动
        中心 = (200 + 帧 * 150) % (长度 - 400) + 200
        return np.exp(-0.5 * ((f - 中心) / 40.0) ** 2)
    if 模式 == "双音":
        谱 = np.zeros(长度)
        for 心, 幅 in ((500, 0.6), (2000, 0.35)):
            谱 += 幅 * np.exp(-0.5 * ((f - 心) / 30.0) ** 2)
        return 谱
    if 模式 == "静音":
        return np.zeros(长度)
    return np.zeros(长度)


