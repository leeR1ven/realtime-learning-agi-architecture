    for 模式 in ("扫频", "双音", "静音"):
        谱 = 造测试频谱(模式)
        t0 = time.perf_counter()
        信号 = 频谱转信号(谱)
        t1 = time.perf_counter()
        输出 = 网.前向传播(信号)
        t2 = time.perf_counter()
        响 = 解码响度(池.激活)
        峰带 = int(np.argmax(响[0]))
        对独占 = bool((池.激活[0::2] ^ 池.激活[1::2]).all())
        print(f"[{模式}] 编码 {1000 * (t1 - t0):.1f}ms | 整帧 {1000 * (t2 - t0):.1f}ms"
              f" | 输入层激活 {int(池.激活.sum())}/{池.总数} | 每对恰一个 {对独占}"
              f" | 输出层激活 {int(输出.sum())} | 最响频带 {峰带} 档 {int(响[0, 峰带])}")

    t0 = time.perf_counter()
    for 帧 in range(10):
        网.前向传播(频谱转信号(造测试频谱("扫频", 帧=帧)))
    t1 = time.perf_counter()
    print(f"连续 10 帧平均: {1000 * (t1 - t0) / 10:.1f}ms/帧（0.1 秒一帧绰绰有余）")
