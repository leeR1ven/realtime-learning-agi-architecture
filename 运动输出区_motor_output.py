class 神经网络:
    """局部连接版：每个神经元只连上一层附近的神经元（首尾成环）"""

    def __init__(self, 输入层, 层数, 连接半径=10,
                 权重范围=0.1, 阈值初值=0.5):
        self.输入层 = 输入层
        self.对数 = 输入层.对数
        self.层数 = 层数
        self.半径 = 连接半径
        self.每层数 = 输入层.总数
        self.输出层数量 = self.每层数  # 最后一层神经元数量（记忆区靠它同步）
        连接数 = 2 * 连接半径 + 1   # 每个神经元连几个邻居

        self.来源 = []
        self.权重 = []
        self.阈值 = [np.full(self.每层数, 阈值初值) for _ in range(层数 - 1)]
        self.普通层激活 = [np.zeros(self.每层数, dtype=bool) for _ in range(层数 - 1)]

        for _ in range(层数 - 1):
            # 目标神经元 j 连上一层 j-半径 ~ j+半径，取模使首尾相接成环
            偏移 = np.arange(-连接半径, 连接半径 + 1)
            目标 = np.arange(self.每层数)
            来源 = (目标[:, None] + 偏移[None, :]) % self.每层数
            权重 = np.random.uniform(0, 权重范围, size=(self.每层数, 连接数))
            self.来源.append(来源)
            self.权重.append(权重)

    def 前向传播(self, 输入信号):
        self.输入层.信号[:] = 输入信号
        self.输入层.更新所有对()
        当前激活 = self.输入层.激活.astype(float)

        for k in range(self.层数 - 1):
            加权和 = (self.权重[k] * 当前激活[self.来源[k]]).sum(axis=1)
            当前激活 = 加权和 >= self.阈值[k]   # 神经元自己的放电门槛
            self.普通层激活[k] = 当前激活
            当前激活 = 当前激活.astype(float)

        return 当前激活


