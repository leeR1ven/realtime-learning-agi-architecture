def 发力转信号(发力):
    """发力数组（肌肉数 个 0~1 数值）-> 池.信号（温度计码）

    每块肌肉占连续 每档对数 对：发力 L 档 = 前 L 对正激活、后面反激活；
    发力 0 = 全反（肌肉放松），发力满 = 全正（最大发力）。"""
    级 = np.clip(np.rint(np.asarray(发力, dtype=float) * 每档对数).astype(int), 0, 每档对数)
    信号 = np.zeros(池.总数)
    for m in range(肌肉数):
        起 = m * 每档对数
        for j in range(每档对数):
            对 = 起 + j
            if j < 级[m]:
                信号[2 * 对] = 1.0
            else:
                信号[2 * 对 + 1] = 1.0
    return 信号


def 解码发力(激活=None):
    """从池.激活读回每块肌肉的发力档（0~每档对数），用来检查编码"""
    if 激活 is None:
        激活 = 池.激活
    正 = 激活[0::2]   # 每对的正神经元是否激活
    return 正.reshape(肌肉数, 每档对数).sum(axis=1)


def 随机乱动(帧数, 步长=0.04, 起点=None):
    """婴儿式随机探索：每帧发力只在上一步附近小步变化（±步长）。

    真实动作是连续平滑的，不会每帧从零随机跳到另一个完全无关的姿势；
    用这种平滑乱动来跑反向记忆，学到的才是"连续动作的路"，
    记忆不会因为随机跳变互相淹没。"""
    发力 = np.random.uniform(0.3, 0.7, size=肌肉数) if 起点 is None else np.asarray(起点, dtype=float).copy()
    for _ in range(帧数):
        yield 发力.copy()
        发力 = np.clip(发力 + np.random.normal(0.0, 步长, size=肌肉数), 0.0, 1.0)


def 镜像投票(码, 强度=1.0):
    """天生互惠返回线（固定连线、不学习、不占新内存、永不遗忘）：
    命令码亮起的神经元沿出生时固定连线逐层往输入侧回传，
    返回每个肌肉特征神经元收到的投票。命令码全灭时返回全 0。"""
    n = 网.每层数
    深层 = np.asarray(码, dtype=bool)
    if not 深层.any():
        return np.zeros(n)
    for k in range(网.层数 - 2, -1, -1):
        深层们 = np.nonzero(深层)[0]
        浅层们 = 网.来源[k][深层们]
        固定权重 = 网.权重[k][深层们]
        信号 = np.zeros(n)
        np.add.at(信号, 浅层们.ravel(), 固定权重.ravel())
        深层 = 信号
    return 深层 * 强度



class 反向赫布网络旧版:
    """反向赫布学习（文档方法）· 紧凑表版（旧版保留作对照）：
    正向网络运行中，"先激活的特征 + 后激活的输出神经元"构成时序对；
    每对在反向网络里记一格 输出神经元 → 特征神经元 的连接。
    一次学会=True 时：同一连接见过一次就固定为 1，重复出现不再加强（"看一眼就记住"）。
    存储用一张二维表（矩阵）：行 = 输出神经元，列 = 特征神经元，
    每格只占 1 字节（学过=1 / 没学过=0），表大小固定 = 输出数 × 特征数，
    学多少条连接、重复多少遍，内存都不再上涨。
    反向使用时：少数输出神经元激活 → 投票给特征 → 特征池配对竞争（每对一个、恰好一半）。
    文档结论：多个特征汇聚到同一输出时，反向是"模糊回溯"（想起所有源头），
    精确锁定需要以后再加"组合密钥(与门)"。
    """

    def __init__(self, 池对象, 窗口距离=None, 本底范围=0.05, 一次学会=True):
        self.池 = 池对象
        self.输入数量 = 池对象.总数
        self.输出数量 = 池对象.总数      # 运动区输出层与特征层宽度相同，所以表是方形的
        self.窗口距离 = 窗口距离          # None = 文档原版全配对；数字 = 只配对因果窗口内
        self.一次学会 = 一次学会          # True(默认) = 见过一次固定权重 1；False = 按次数累加
        if 一次学会:
            self.矩阵 = np.zeros((self.输出数量, self.输入数量), dtype=bool)
        else:
            self.矩阵 = np.zeros((self.输出数量, self.输入数量), dtype=np.uint32)
        self.本底 = np.random.uniform(0, 本底范围, size=self.输入数量)
        self.学过的条数 = 0

    def 条数(self):
        """统计用：已经学过的不同连接数（内存不会随它上涨）"""
        return self.学过的条数

    def 学习一帧(self, 先特征, 后输出):
        """先特征：先激活的特征(0/1)；后输出：后激活的输出神经元(0/1)"""
        后们 = np.nonzero(后输出)[0]
        先们 = np.nonzero(先特征)[0]
        if len(后们) == 0 or len(先们) == 0:
            return
        if self.窗口距离 is None:
            # 整片铺：所有(输出, 特征)组合一次填上；已经填过的不重复计数
            子块 = self.矩阵[np.ix_(后们, 先们)]
            if self.一次学会:
                self.学过的条数 += int(子块.size) - int(子块.sum())
                self.矩阵[np.ix_(后们, 先们)] = True
            else:
                self.学过的条数 += int(子块.size) - int(np.count_nonzero(子块))
                self.矩阵[np.ix_(后们, 先们)] += 1
        else:
            # 只连环形窗口内的（窗口限制版，保留给需要局部限制的用法）
            n = self.输入数量
            for o in 后们:
                距离 = np.minimum(np.abs(先们 - o), n - np.abs(先们 - o))
                候选 = 先们[距离 <= self.窗口距离]
                if len(候选) == 0:
                    continue
                if self.一次学会:
                    self.学过的条数 += int(len(候选)) - int(self.矩阵[o, 候选].sum())
                    self.矩阵[o, 候选] = True
                else:
                    self.学过的条数 += int(len(候选)) - int(np.count_nonzero(self.矩阵[o, 候选]))
                    self.矩阵[o, 候选] += 1

    def 前向(self, 输出激活):
        """输出层少数神经元激活 → 反向激活特征神经元（返回池.激活，每对一个）"""
        输出们 = np.nonzero(输出激活)[0]
        if len(输出们) == 0:
            投票 = np.zeros(self.输入数量)
        else:
            投票 = self.矩阵[输出们].sum(axis=0, dtype=np.int64)
        self.池.信号[:] = self.本底 + 投票
        self.池.更新所有对()
        return self.池.激活
class 反向赫布网络:
    """运动反向联想网络 —— 纯连接 + 发信号（没有查表、没有搜索）。

    连接 = 一张固定的"命令神经元 × 肌肉特征神经元"突触矩阵
    （出生就把内存占好，之后学多少条都不再涨内存）。
    正向跑动作时，"命令码亮起的神经元"与"当时激活的肌肉特征"同帧点亮，
    突触就 +1（最多加到 封顶，防止某一条被无限加强）。

    三个规则让它不退化、不遗忘、又不怕没见过的命令码：
      ① 单调只增：学会的突触永远保留，运动记忆绝不遗忘；
      ② 门控省位：每次先自己试召回，若召回已经接近这次的真实肌肉
         （差异神经元数 ≤ 门槛）说明这条路早已学会，就不新增突触——
         反复经历同一类动作不会把记忆互相铺满淹没；
      ③ 天生底版：召回时永远叠一条固定镜像线的微弱投票，
         再新的命令码也能先给出肌肉的大概位置（不学习、不占内存）。
    召回 = 突触投票 + 天生底版 → 特征池每对竞争（每对恰激活一个）。
    """

    def __init__(self, 池对象, 窗口距离=None, 本底范围=0.05, 一次学会=True,
                 门槛=None, 封顶=8, 镜像强度=1.0):
        self.池 = 池对象
        self.输入数量 = 池对象.总数
        self.输出数量 = 池对象.总数   # 运动区输出层与特征层同宽，所以是方形
        self.窗口距离 = 窗口距离
        self.一次学会 = 一次学会
        # 一次学会=True：突触到 1 就饱和（见过一次即固定）；False：最多叠到 封顶
        self.封顶 = 1 if 一次学会 else int(封顶)
        # 门槛默认 = 0.4×对数 个神经元：召回和真实肌肉差异少于约 2/5 就算"已学会"
        self.门槛 = 0.4 * 池对象.对数 if 门槛 is None else 门槛
        self.镜像强度 = 镜像强度
        self.矩阵 = np.zeros((self.输出数量, self.输入数量), dtype=np.uint8)
        self.本底 = np.random.uniform(0, 本底范围, size=self.输入数量)
        self.学过的条数 = 0

    def 条数(self):
        """已经学过的不同突触连接条数（内存固定，不随它上涨）"""
        return self.学过的条数

    def 学习一帧(self, 先特征, 后输出):
        """先特征：本帧激活的肌肉特征(0/1)；后输出：命令码亮起的神经元(0/1)"""
        后们 = np.nonzero(后输出)[0]
        先们 = np.nonzero(先特征)[0]
        if len(后们) == 0 or len(先们) == 0:
            return
        # ② 门控：先用已有突触试召回，若已接近这次的真实肌肉 → 早已学会，不再记
        投票 = self.矩阵[后们].sum(axis=0, dtype=np.int64)
        if 投票.sum() > 0:
            自测池 = 特征神经元池(self.池.对数)
            自测池.信号[:] = self.本底 + 投票
            自测池.更新所有对()
            if int((自测池.激活 ^ 先特征).sum()) <= self.门槛:
                return
        if self.窗口距离 is not None:
            # 只连环形窗口内的（需要局部限制时用）
            n = self.输入数量
            新增 = 0
            for o in 后们:
                距离 = np.minimum(np.abs(先们 - o), n - np.abs(先们 - o))
                候选 = 先们[距离 <= self.窗口距离]
                if len(候选) == 0:
                    continue
                行 = self.矩阵[o]
                新增 += int((行[候选] == 0).sum())
                行[候选] = np.minimum(行[候选] + 1, self.封顶)
            self.学过的条数 += 新增
            return
        # ① 单调加强：命令码亮起的神经元，向本帧激活的肌肉特征各加 1（最多到 封顶）
        子块 = self.矩阵[后们].copy()
        新增 = int(((子块 == 0) & (先特征[None, :] != 0)).sum())
        self.矩阵[后们] = np.minimum(子块 + (先特征.astype(np.uint8))[None, :], self.封顶)
        self.学过的条数 += 新增

    def 前向(self, 输出激活):
        """命令码少数神经元激活 → 反向激活肌肉特征（返回池.激活，每对一个）"""
        输出们 = np.nonzero(输出激活)[0]
        if len(输出们) == 0:
            投票 = np.zeros(self.输入数量)
        else:
            投票 = self.矩阵[输出们].sum(axis=0, dtype=np.int64)
        # ③ 天生底版：叠一条固定镜像线的微弱投票
        # 只有宽度和本文件全局运动网一致时才叠（闭环仿真里自建的小型
        # 反向网络没有对应的全局镜像线，宽度不同就跳过这条不学习的天生底版）
        if self.输入数量 == 网.每层数:
            投票 = 投票 + 镜像投票(输出激活, 强度=self.镜像强度)
        self.池.信号[:] = self.本底 + 投票
        self.池.更新所有对()
        return self.池.激活


def 发力档MAE(找回激活, 发力):
    """找回的肌肉激活 → 发力档，和真实发力的档位差取平均（测试用）"""
    正 = 找回激活[0::2].reshape(肌肉数, 每档对数).sum(axis=1)
    期望 = np.clip(np.rint(发力 * 每档对数).astype(int), 0, 每档对数)
    return float(np.abs(正 - 期望).mean())


