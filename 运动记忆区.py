import numpy as np
from 海马体时间区 import 时钟
from 权重连接管理 import 连接表
from 运动输出区 import 网


class 记忆区:
    """运动记忆区：特征神经元 + 时序赫布权重；时间由共享时钟（海马体时间区）驱动

    记录内容：运动输出区每一帧亮起的"输出层命令模式"（方案1，和视觉/听觉记忆区一致：
    记大脑发出的命令序列；要真正动肌肉时，由运动输出区的反向赫布网络展开成肌肉状态）。
    """

    def __init__(self, 神经元数量):
        self.总数 = 神经元数量
        self.激活 = np.zeros(神经元数量, dtype=bool)   # 特征神经元激活状态
        self.特征到时间 = 连接表()   # 特征编号 → {时间编号: 权重}（带定期遗忘）
        self.时间到特征 = 连接表()   # 时间编号 → {特征编号: 权重}（带定期遗忘）

    def 学习(self, 旧时间, 新时间, 新特征):
        """一个内部时间步（0.05 秒）的时序赫布学习。
        旧时间/新时间由共享时钟给出；新特征 = 这一帧记忆区的特征激活状态。
        """
        # 规则：上一帧的特征 → 下一格时间神经元
        for f in np.nonzero(self.激活)[0]:
            self.特征到时间.学习(f, 新时间)

        # 规则：上一格时间神经元 → 下一帧的特征
        for f in np.nonzero(新特征)[0]:
            self.时间到特征.学习(旧时间, f)

        self.激活[:] = 新特征
        self.特征到时间.维护()   # 连接达到警戒线后定期整体衰减，防无限增长
        self.时间到特征.维护()

    def 回忆(self, 特征模式, 步数=10, 阈值=1):
        """给一组特征，找到关联时间，沿共享时间环连续播放"""
        得分 = np.zeros(时钟.时间神经元数量)
        for f in np.nonzero(特征模式)[0]:
            for t, w in self.特征到时间.查(f).items():
                得分[t] += w

        if 得分.max() == 0:
            return []   # 这些特征没有学过任何时间关联

        当前时间 = int(np.argmax(得分))
        播放 = []
        for _ in range(步数):
            特征 = np.zeros(self.总数, dtype=bool)
            for f, w in self.时间到特征.查(当前时间).items():
                if w >= 阈值:
                    特征[f] = True
            播放.append((当前时间, 特征))
            当前时间 = (当前时间 + 1) % 时钟.时间神经元数量
        return 播放


if __name__ == "__main__":
    print("时间神经元数量:", 时钟.时间神经元数量)
    print("一帧秒数:", 时钟.每步秒数 * 时钟.每帧步数)
    print("绕一圈小时:", 时钟.时间神经元数量 * 时钟.每步秒数 / 3600)

    记忆 = 记忆区(网.输出层数量)

    # ===== 婴儿乱动阶段：每 0.1 秒一帧 =====
    # 1) 随机给肌肉层信号（每对随机一个发力/放松）
    # 2) 经运动神经网络 → 输出层亮起少数神经元 = 大脑这帧的命令模式
    # 3) 记忆区把命令模式按时间顺序记下（每帧占 每帧步数 个时间步）
    帧数 = 30
    历史 = []
    for _ in range(帧数):
        信号 = np.random.uniform(0.0, 1.0, size=网.输入层.总数)
        输出模式 = 网.前向传播(信号).astype(bool).copy()
        历史.append(输出模式)
        for _ in range(时钟.每帧步数):
            旧时间, 新时间 = 时钟.走一步()
            记忆.学习(旧时间, 新时间, 输出模式)
    print(f"乱动学习完成：{帧数} 帧，每帧命令模式激活数约 {int(历史[0].sum())}")

    # ===== 回忆测试：从第 5 帧的命令模式开始，沿时间环连续播放 =====
    起点 = 5
    播放 = 记忆.回忆(历史[起点], 步数=12)
    正确 = 0
    for i, (时间, 特征) in enumerate(播放):
        # 每帧占 每帧步数 个时间步，所以播放步 i 对应真实历史里的第 起点+1+i//每帧步数 帧
        真实帧 = 历史[起点 + 1 + i // 时钟.每帧步数]
        重合 = int((特征 & 真实帧).sum())
        全对 = 重合 == 真实帧.sum() and 特征.sum() == 真实帧.sum()
        正确 += int(全对)
        print("时间", 时间, "→ 激活数:", 特征.sum(),
              "| 与真实下一帧重合:", 重合, "/", 真实帧.sum(), "|", "对" if 全对 else "错")
    print(f"回忆正确率: {正确} / {len(播放)}")
