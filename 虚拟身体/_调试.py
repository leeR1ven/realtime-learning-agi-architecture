import numpy as np
import 身体 as B

# 1) 锁定成刚体: 三个角速度保持一致 应该像一根直杆绕踝倒
身 = B.建身体(角度=[0.15]*3, 角速=[0.0]*3)
B.阻尼[:] = [0,0,0]

def 报告(tag, 身):
    st = B.读状态(身)
    关, 质心 = B.关节位置质心(身["角度"])
    总质量 = sum(B.节表[i][2] for i in range(3))
    v关 = [np.zeros(2) for _ in range(4)]
    E = 0.0
    for i in range(3):
        ω = 身["角速"][i]
        r质 = B.节表[i][3] * B.方向(身["角度"][i])
        r关 = B.节表[i][1] * B.方向(身["角度"][i])
        v质 = v关[i] + B.叉(ω, r质)
        v关[i+1] = v关[i] + B.叉(ω, r关)
        E += 0.5*B.节表[i][2]*(v质@v质) + 0.5*B.节表[i][4]*ω*ω + B.节表[i][2]*B.重力*质心[i][1]
    print(f"{tag}: θ={身['角度']} ω={身['角速']} E={E:.3f}")

报告("起点", 身)
for k in range(1000):
    B.物理一步(身, np.zeros(3), 0.002)
    if k in (100, 300, 600, 900):
        报告(f"t={(k+1)*0.002:.2f}", 身)
报告("终点2s", 身)
