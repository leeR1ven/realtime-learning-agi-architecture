"""_调试7.py —— 跳步防倒参数扫描：找出(升速,空中姿态目标,起跳时机)能扛住大推力的组合
用法: python _调试7.py
"""
import numpy as np
import 身体 as B
import 感官本能 as S

冷却 = 0.25          # 两次起跳最短间隔
最大时长 = 5.0

def 试(冲量, 升速, 踝空, 膝空, 髋空, ω阈值, 角度阈值):
    S.踝空目标 = 踝空
    S.膝空目标 = 膝空
    S.髋空目标 = 髋空
    S.跳升速 = 升速
    S.重置本能()
    身 = B.建身体()
    B.加推力(身, 冲量)
    上次跳 = -9.0
    跳数 = 0
    while 身["时间"] < 最大时长:
        st = B.读状态(身)
        if 身["模式"] == "空":
            扭矩 = S.空中本能(st)
        else:
            _, 扭矩, 迈 = S.本能连接(st)
            if (身["时间"] - 上次跳 > 冷却 and 身["时间"] > 0.001
                    and ((st["前倾"] > 角度阈值 and abs(st["前倾速度"]) > 0.8)
                         or (abs(st["前倾速度"]) > ω阈值 and abs(st["前倾"]) > 0.03)
                         or abs(st["前倾"]) > 0.22)):
                扭矩 = S.空中本能(st)
                vx = float(np.clip(st["质心速度"][0], -3.0, 3.0))
                B.起跳(身, 升速)
                身["基速"][0] = vx   # 用真实质心水平速度，替代角速度x高度估计
                上次跳 = 身["时间"]
                跳数 += 1
        for _ in range(10):
            if 身["模式"] == "空":
                if B.悬空一步(身, 扭矩):
                    break
            else:
                B.物理一步(身, 扭矩)
        st = B.读状态(身)
        if 身["模式"] == "站":
            倒, 因 = B.摔倒了吗(st)
            if 倒:
                return False, 因, 跳数, st["前倾"]
    return True, "", 跳数, 0.0

