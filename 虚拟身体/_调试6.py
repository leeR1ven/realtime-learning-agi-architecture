"""_调试6.py —— 单次推力+跳步防倒的逐帧追踪(每次跳只允许一跳前先细看)
用法: python _调试6.py [冲量] [升速]  (默认 +24 / 1.5)
"""
import sys
import numpy as np
import 身体 as B
import 感官本能 as S

冲量 = float(sys.argv[1]) if len(sys.argv) > 1 else 24.0
升速 = float(sys.argv[2]) if len(sys.argv) > 2 else S.跳升速
身 = B.建身体()
S.重置本能()
B.加推力(身, 冲量)
上次跳 = -9.0
次 = 0
跳数 = 0
print(f"推力={冲量:+.0f}N·s  升速={升速}  控制周期={S.控制周期}s")
while 身["时间"] < 4.0:
    st = B.读状态(身)
    if 身["模式"] == "空":
        扭矩 = S.空中本能(st)
    else:
        _, 扭矩, 迈 = S.本能连接(st)
        if (迈 and 身["时间"] - 上次跳 > 0.45
                and (abs(st["前倾速度"]) > 1.8 or abs(st["前倾"]) > 0.25)):
            扭矩 = S.空中本能(st)
            B.起跳(身, 升速)
            上次跳 = 身["时间"]
            跳数 += 1
            a = st["角度"]; o = st["角速"]
            print(f"[跳{跳数}] t={身['时间']:.3f} 起跳: 前倾={st['前倾']*57.3:.1f}° "
                  f"前倾速={st['前倾速度']:.2f} 基速={身['基速'].round(2)} "
                  f"踝={a[0]*57.3:.0f}° 膝={a[1]*57.3:.0f}° 髋={a[2]*57.3:.0f}° "
                  f"躯干速={o[2]:.2f}")
    for _ in range(10):
        if 身["模式"] == "空":
            if B.悬空一步(身, 扭矩):
                st = B.读状态(身)
                a = st["角度"]; o = st["角速"]
                print(f"[落地{跳数}] t={身['时间']:.3f} 脚x={身['脚x']:+.3f} "
                      f"踝={a[0]*57.3:+.0f}° 膝={a[1]*57.3:+.0f}° 髋={a[2]*57.3:+.0f}° "
                      f"前倾={st['前倾']*57.3:+.1f}° 前倾速={st['前倾速度']:+.2f} "
                      f"角速={o.round(2)} 髋高={st['髋高度']:.2f}")
                break
        else:
            B.物理一步(身, 扭矩)
    st = B.读状态(身)
    次 += 1
    if 次 % 4 == 0:
        a = st["角度"]; o = st["角速"]
        print(f"t={身['时间']:.3f} {身['模式']} 脚x={身['脚x']:+.3f} 基x={身.get('基x',0):+.2f}"
              f" 踝={a[0]*57.3:+5.1f} 膝={a[1]*57.3:+5.1f} 髋={a[2]*57.3:+5.1f} "
              f"前倾={st['前倾']*57.3:+6.1f} 髋高={st['髋高度']:.2f} 前倾速={st['前倾速度']:+.2f}")
    if 身["模式"] == "站":
        倒, 因 = B.摔倒了吗(st)
        if 倒:
            print("摔倒:", 因, " t=", round(身["时间"], 3))
            break
else:
    print("4 秒内没摔倒，站稳")