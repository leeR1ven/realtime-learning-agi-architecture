"""权重连接管理_weight_manager.py —— 赫布学习连接共用的"增长 → 定期遗忘"规则

只用于需要赫布学习的连接（三个记忆区、前额叶联想区）：
  先激活 → 后激活 出现一次，权重加 强化量。

提前定好、固定不变的神经网络（视觉/听觉/运动前处理网络、
前额叶正向网络、天生互惠返回线）不走这套规则，权重永远不改。

规则（防止连接无限增加）：
  1. 每次使用：连接权重加 强化量（默认 1）。
  2. 连接条数达到 警戒线 后，每隔 衰减间隔 次维护（≈帧）整体衰减一次：
     所有权重 × 衰减率。
  3. 衰减后权重低于 消失下限 的连接直接删除 —— 少用的连接反复被衰减，
     最终归零消失；常用连接虽然也被衰减，但每次使用又加回权重，
     于是停在平衡值附近维持不变。

调参（想忘得慢：衰减间隔调大、衰减率调接近 1、消失下限调小；
想忘得快：反过来调小/调大）。
"""

# ===== 全局默认参数：想整体调整就只改这里 =====
强化量   = 1.0      # 每使用一次，权重加多少
衰减率   = 0.9      # 整体衰减时，所有权重 × 0.9
消失下限 = 0.05     # 权重衰减到低于它 → 删除这条连接
警戒线   = 100000   # 连接条数到达这条线，才开始周期衰减
衰减间隔 = 200      # 到达警戒线后，每隔多少次维护（≈帧）衰减一次


class 连接表:
    """一个方向的权重连接：起点 → {终点: 权重}

    内部结构和原来记忆区用的字典一样（外面仍可 len / values / get 访问），
    只是加上了"学习加权重 + 超标后定期整体衰减"的管理。
    """

    def __init__(self, 强化量=强化量, 衰减率=衰减率, 消失下限=消失下限,
                 警戒线=警戒线, 衰减间隔=衰减间隔):
        self.强化量 = 强化量
        self.衰减率 = 衰减率
        self.消失下限 = 消失下限
        self.警戒线 = 警戒线
        self.衰减间隔 = 衰减间隔
        self.表 = {}          # 起点 → {终点: 权重}
        self.连接条数 = 0      # 当前不同连接的条数（缓存，不用每次现数）
        self.维护次数 = 0      # 调过多少次维护（≈过了多少帧）
        self.上次衰减维护 = -衰减间隔

    def __len__(self):
        """和原来 len(外层字典) 一样：起点（行）的个数"""
        return len(self.表)

    def values(self):
        """和原来 外层字典.values() 一样：每一行的 {终点: 权重}"""
        return self.表.values()

    def get(self, 起点, 默认=None):
        """和原来 外层字典.get 一样：取某一行的 {终点: 权重}"""
        return self.表.get(起点, 默认)

    def 查(self, 起点):
        """取某一起点的 {终点: 权重}，没有就返回空行"""
        return self.表.get(起点, {})

    def 学习(self, 起点, 终点, 增量=None):
        """赫布增量：这条连接被使用一次，权重 +强化量"""
        起点 = int(起点)
        终点 = int(终点)
        行 = self.表.setdefault(起点, {})
        旧 = 行.get(终点, 0.0)
        行[终点] = 旧 + (self.强化量 if 增量 is None else 增量)
        if 旧 == 0.0:
            self.连接条数 += 1   # 新连接

    def 维护(self):
        """每个时间步（帧）调一次：到达警戒线后，每隔 衰减间隔 帧整体衰减"""
        self.维护次数 += 1
        if self.连接条数 >= self.警戒线 and \
                self.维护次数 - self.上次衰减维护 >= self.衰减间隔:
            self.整体衰减()
            self.上次衰减维护 = self.维护次数
            return True
        return False

    def 整体衰减(self):
        """所有权重 × 衰减率；低于消失下限的连接删除；空行也删掉"""
        for 行 in self.表.values():
            for 终点 in list(行):
                权重 = 行[终点] * self.衰减率
                if 权重 < self.消失下限:
                    del 行[终点]
                    self.连接条数 -= 1
                else:
                    行[终点] = 权重
        for 起点 in [a for a, 行 in self.表.items() if not 行]:
            del self.表[起点]

    def 条数(self):
        """当前不同连接的条数（已缓存，O(1)）"""
        return self.连接条数


if __name__ == "__main__":
    # ---- 自检：用很小的警戒线，验证"常用留着、少用消失、总量封顶" ----
    表 = 连接表(警戒线=100, 衰减间隔=5, 衰减率=0.5,
                消失下限=0.01, 强化量=1.0)

    # 第一阶段：灌入 300 条只用一次的一次性连接，让条数超过警戒线
    for 轮 in range(5):
        for j in range(60):
            表.学习(轮, j)
        表.维护()
    print("灌入 300 条一次性连接后条数:", 表.条数())

    # 第二阶段：一边持续使用"常用连接"，一边偶尔用"偶尔连接"，
    # 一次性连接不再使用，等着被衰减清掉
    for 帧 in range(60):
        for _ in range(3):
            表.学习(888, 999)          # 常用：每帧都用
        if 帧 % 10 == 0:
            表.学习(777, 778)          # 偶尔：每 10 帧用一次
        表.维护()

    常用权重 = 表.查(888).get(999, 0.0)
    偶尔权重 = 表.查(777).get(778, 0.0)
    一次性剩余 = 表.条数() - (1 if 常用权重 else 0) - (1 if 偶尔权重 else 0)
    print(f"总条数: {表.条数()}（被压住不再无限涨）")
    print(f"常用连接权重: {常用权重:.3f}（仍留着，反复使用不消失）")
    print(f"偶尔连接权重: {偶尔权重:.3f}（用得少，权重被压得很低）")
    print("一次性连接剩余条数:", 一次性剩余, "（大部分已被衰减删除）")
