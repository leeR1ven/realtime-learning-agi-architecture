def 扩散(模式, 段宽, 半宽):
    """把每个亮着的神经元连同段内前后 ±半宽 一起点亮（每段内首尾成环）"""
    if 半宽 <= 0:
        return np.asarray(模式, dtype=bool)
    out = np.zeros(段宽, dtype=bool)
    for p in np.nonzero(模式)[0]:
        for d in range(-半宽, 半宽 + 1):
            out[(p + d) % 段宽] = True
    return out


class 前额叶神经网络:
    """前额叶网络：三路稀疏激活拼成输入，局部连接成环、阈值放电（和其他区一样的稀疏网络）。

    输入三路（每路 8000 个神经元，只亮二三十个的稀疏码）：
      1. 视觉区输出层激活（视觉"看懂"了什么）
      2. 听觉区输出层激活（听觉"听懂"了什么）
      3. 运动区输入 = 运动区大脑侧的稀疏激活（运动输出层的命令模式；
         运动区是大脑往外发信号，用的是反向网络，所以取的是这一侧）
    稀疏码太稀，直接进固定阈值的局部网络会一帧都推不亮，
    所以每一路先各自"扩散"（每个亮点连同周围 ±扩散宽度 一起点亮成小亮斑）再进网络。
    """

    def __init__(self, 输入数量, 层数=3, 连接半径=10, 权重范围=0.1,
                 隐藏层阈值=0.55, 输出层阈值=1.2, 扩散宽度=10,
                 汇合比例=0.0, 汇合每路线数=0, 汇合阈值倍数=1.0, 分段宽=None):
        """人脑式布线的固定网络：多数细胞是单路"身份细胞"（只收本段），
        少数"汇合细胞"额外收另外两路的大量长程线、阈值也抬高 ——
        只有多路信号一起来时汇合细胞才放电（类似前额叶的混合选择性/汇合区）。"""
        self.输入数量 = 输入数量
        self.每层数 = 输入数量
        self.输出层数量 = 输入数量
        self.层数 = 层数
        self.半径 = 连接半径
        self.扩散宽度 = 扩散宽度
        self.汇合比例 = 汇合比例
        self.汇合每路线数 = 汇合每路线数
        self.汇合阈值倍数 = 汇合阈值倍数
        self.分段宽 = 分段宽
        self.汇合掩码 = []
        连接数 = 2 * 连接半径 + 1
        目标 = np.arange(输入数量)
        偏移 = np.arange(-连接半径, 连接半径 + 1)
        self.来源 = []
        self.权重 = []
        self.阈值 = []
        块起点, 块终点 = None, None
        加跨线 = 汇合比例 > 0 and 汇合每路线数 > 0
        if 加跨线:
            if 分段宽 is None or len(分段宽) != 3 or sum(分段宽) != 输入数量:
                raise ValueError("汇合比例>0 时必须传 分段宽=[视宽,听宽,运宽]，且三段相加等于输入数量")
            if not (0.0 < 汇合比例 <= 1.0):
                raise ValueError("汇合比例 必须在 (0,1]")
            块起点 = [0, 分段宽[0], 分段宽[0] + 分段宽[1]]
            块终点 = [分段宽[0], 分段宽[0] + 分段宽[1], 输入数量]
        汇合列数 = 2 * 汇合每路线数
        for k in range(层数 - 1):
            局部来源 = (目标[:, None] + 偏移[None, :]) % 输入数量
            局部权重 = np.random.uniform(0, 权重范围, size=(输入数量, 连接数))
            # 中间层用一个阈值，最后一层（输出层）用更高的阈值，保证只亮少量神经元
            用哪个阈值 = 输出层阈值 if k == 层数 - 2 else 隐藏层阈值
            self.阈值.append(np.full(输入数量, 用哪个阈值))
            if 加跨线 and k == 层数 - 2:
                # 只在输出这一级布"汇合细胞"：从三段里按 汇合比例 随机挑一批，
                # 让它们额外收另外两路各 汇合每路线数 根长程线，并抬高阈值。
                汇合数 = int(round(输入数量 * 汇合比例))
                掩 = np.zeros(输入数量, dtype=bool)
                掩[np.random.choice(输入数量, size=汇合数, replace=False)] = True
                self.汇合掩码.append(掩)
                self.阈值[-1][掩] = 用哪个阈值 * 汇合阈值倍数
                跨来源 = np.empty((输入数量, 汇合列数), dtype=np.int64)
                跨权重 = np.zeros((输入数量, 汇合列数))
                for b in range(3):
                    块行们 = np.arange(块起点[b], 块终点[b])
                    汇合行 = 块行们[掩[块行们]]
                    其他段 = [j for j in range(3) if j != b]
                    for 列, j in enumerate(其他段):
                        col0 = 列 * 汇合每路线数
                        col1 = col0 + 汇合每路线数
                        跨来源[块行们, col0:col1] = np.random.randint(
                            块起点[j], 块终点[j], size=(块行们.shape[0], 汇合每路线数))
                        跨权重[汇合行, col0:col1] = np.random.uniform(
                            0, 权重范围, size=(汇合行.shape[0], 汇合每路线数))
                self.来源.append(np.concatenate([局部来源, 跨来源], axis=1))
                self.权重.append(np.concatenate([局部权重, 跨权重], axis=1))
            else:
                self.来源.append(局部来源)
                self.权重.append(局部权重)
                self.汇合掩码.append(np.zeros(输入数量, dtype=bool))
        self.普通层激活 = [np.zeros(输入数量, dtype=bool) for _ in range(层数 - 1)]
        self.输入激活 = np.zeros(输入数量, dtype=bool)

    def 前向传播(self, 视觉输出, 听觉输出, 运动输入, 输入衰减=0.0):
        """三路输入都是 0/1 数组（各自区里"哪几个神经元亮了"），长度相同"""
        # 三路宽度可以不同（视觉大、听觉中、运动小），各自按自己的宽度扩散后拼接
        if len(视觉输出) + len(听觉输出) + len(运动输入) != self.输入数量:
            raise ValueError("三路拼接长度与 输入数量 不一致，请检查各区输入层宽度")
        self.输入激活[:] = np.concatenate([
            扩散(视觉输出, len(视觉输出), self.扩散宽度),
            扩散(听觉输出, len(听觉输出), self.扩散宽度),
            扩散(运动输入, len(运动输入), self.扩散宽度)])
        当前激活 = self.输入激活.astype(float) * (1.0 - 输入衰减)  # 专注闸门：专注时外界信号被抑制池压弱
        for k in range(self.层数 - 1):
            加权和 = (self.权重[k] * 当前激活[self.来源[k]]).sum(axis=1)
            当前激活 = 加权和 >= self.阈值[k]
            self.普通层激活[k] = 当前激活
            当前激活 = 当前激活.astype(float)
        return 当前激活


class 天生互惠返回线:
    """前额叶 → 输入侧 的"天生互惠返回线"（出生接好、固定不动、不学习、不遗忘）

    大脑的前额叶和感觉区之间天生就有一来一回两套线：
      去路 = 各区 → 前额叶（正向网络，随机出生权重）；
      回路 = 前额叶 → 各区（本类）：把正向每一层"谁和谁相邻"的邻居表原样倒过来，
            输出层亮起的神经元沿固定连线，把信号一层层送回输入侧。
    权重 = 正向网络出生时的固定权重，从不改动、从不学习：
      · 永远可用：对没经历过的新想法也能给提示，不会退化、不会遗忘、不占新内存
      · 天生是"粗"的：只能送回大概位置（覆盖有限、还带多余），做不了逐细胞精确还原
    精确还原交给海马体：前额叶亮起 → 海马索引锁定时间细胞 → 记忆区把那一刻补全。
    """

    def __init__(self, 前额网, 返回保留比例=0.3):
        self.输入数量 = 前额网.输入数量
        self.每层数 = 前额网.每层数
        self.层数 = 前额网.层数
        # 直接借用正向的邻居表与出生权重（只读），方向倒过来用就是互惠回路
        self.来源 = 前额网.来源
        self.权重 = 前额网.权重
        self.返回保留比例 = 返回保留比例

    def 返回(self, 输出激活, 抑制量=0.0):
        """前额叶输出层 0/1 → 送回输入侧的提示 0/1（长度 = 输入数量）"""
        n = self.每层数
        深层激活 = np.asarray(输出激活, dtype=bool)
        if not 深层激活.any():
            return np.zeros(n, dtype=bool)
        for k in range(self.层数 - 2, -1, -1):
            深层们 = np.nonzero(深层激活)[0]   # 这一轮亮着的深层神经元
            浅层们 = self.来源[k][深层们]       # 它们出生时连着的浅层神经元
            固定权重 = self.权重[k][深层们]     # 每条连线出生时的固定权重
            信号 = np.zeros(n)
            np.add.at(信号, 浅层们.ravel(), 固定权重.ravel())
            信号 = 信号 * (1.0 - 抑制量)   # 专注闸门：不想回忆时整条回忆通路压到 0
            # 只有回传信号够强的浅层神经元才亮（比例门限，出生权重随机也不怕）
            峰值 = 信号.max()
            if 峰值 <= 0:
                return np.zeros(n, dtype=bool)
            深层激活 = 信号 >= self.返回保留比例 * 峰值
        return 深层激活


class 海马索引:
    """前额叶 → 海马体时间神经元 的联想索引（只记"哪一刻"，不存内容）

    经历时：前额叶输出模式与当时亮着的时间细胞同时亮，就在
    时间细胞 → 输出神经元 之间记一格固定连接（同一对只记一次，
    重复经历不加重 —— 学一次就记住，不会越记越模糊）。
    回忆时：给一个前额叶输出模式，每个记过的时间细胞"举手报数"
    （它当时亮过的输出里，有几个和现在一样）；举最多的时间细胞胜出
    = 前额叶"想到了哪一刻"。那一刻各区是什么（内容），由各记忆区按
    胜出的时间细胞把原始模式播放出来补全 —— 索引自己不存内容。
    没凑够票（票数比例 < 相对门槛）= 没见过这一刻，不乱回放记忆。
    """

    def __init__(self):
        self.时间到输出 = {}   # 时间细胞 → 当时亮过的前额输出编号集合（一次学会）

    def 学习(self, 时间, 输出模式):
        """经历一帧时调用：输出模式与 时间 同时亮 → 记一格固定连接"""
        for o in np.nonzero(输出模式)[0]:
            self.时间到输出.setdefault(int(时间), set()).add(int(o))

    def 连接数(self):
        """统计用：已经记过的不同连接条数"""
        return sum(len(亮过) for 亮过 in self.时间到输出.values())

    def 锁定时间(self, 输出模式, 相对门槛=0.7):
        """回忆：输出模式 → 时间细胞举手投票 → (时间, 票数比例)；不够票 = (None, 比例)

        平票规则：优先选"当时亮过的输出集合大小和现在完全一样"的时间细胞。
        大集合只是碰巧把现在这些小集合全包含进去，不算真的同一个时刻。"""
        输出们 = set(np.nonzero(输出模式)[0].tolist())
        if not 输出们:
            return None, 0.0
        最佳时间, 最佳票, 最佳键 = None, 0, (-1, -1)
        for t, 当时亮过 in self.时间到输出.items():
            票 = len(输出们 & 当时亮过)
            if 票 == 0:
                continue
            键 = (票, -abs(len(当时亮过) - len(输出们)))
            if 键 > 最佳键:
                最佳键, 最佳票, 最佳时间 = 键, 票, t
        比例 = 最佳票 / len(输出们) if 最佳票 else 0.0
        return (最佳时间 if 比例 >= 相对门槛 else None), 比例


    def 锁定胜出(self, 输出模式, 底票=80, 领先=40):
        """票数胜出锁定（给几百个细胞一起亮的真实念头用）：
        每个记过的时间细胞数一数"当时亮过的输出里有几个现在也亮"，
        票最多且明显领先第二名的才锁定。全新念头只是碰巧撞上一两票、
        领先极小，所以返回 None —— 不乱回放、不编造。"""
        输出们 = set(np.nonzero(输出模式)[0].tolist())
        if not 输出们:
            return None, 0.0
        票们 = sorted((len(输出们 & 当时亮过), t)
                      for t, 当时亮过 in self.时间到输出.items())
        if not 票们:
            return None, 0.0
        第一票, 第一时间 = 票们[-1]
        第二票 = 票们[-2][0] if len(票们) > 1 else 0
        胜出 = 第一票 >= 底票 and 第一票 - 第二票 >= 领先
        return (第一时间 if 胜出 else None), 第一票


class 前额叶联想区:
    """前额叶内部的"联想记忆 + 抑制门控"区：让念头一个接一个连成串（连续的记忆）

    三类神经元布在同一层环上（每 每段 个正常神经元配一个抑制/去抑制位点）：
      正常神经元  = 念头细胞（一个念头 = 其中一小撮细胞亮着）
      抑制神经元  = 压自己位点附近的正常神经元（强度 = 整体强度 × (静息 + 局部反馈)）
      去抑制神经元 = 专门压抑制神经元：门一开，本来的抑制被抵消，附近的念头容易亮
    学习（时序赫布，方向 = 先激活 → 后激活）：
      · 上一帧念头 a → 下一帧念头 b：记一格 联想[a → b]（同一对再现就加粗）
      · 上一帧念头 a → 下一帧念头附近位点的去抑制神经元：记一格 去抑[a → 位点]
    回忆（内部微步，一帧内可连走好几步）：
      · 当前念头 → 给学过的后继投票（后继细胞收到"它曾经跟过谁"的分）
      · 当前念头 → 给学过后继的位点开门（去抑制抵消抑制）
      · 没开门的位点仍有 整体强度 × 抑制 压着 → 无关念头、噪声亮不起来
    动态整体抑制（自我平衡）：
      · 这一微步亮的念头细胞太少（< 目标下限）→ 整体抑制调低（变容易激活）
      · 太多（> 目标上限）→ 整体抑制调高（防止一次冒出太多记忆）
    """

    def __init__(self, 宽度, 每段=40, 门槛=2.0,
                 目标下限=4, 目标上限=24,
                 目标比例下限=0.5, 目标比例上限=1.3,
                 强度初值=1.0, 强度下限=0.15, 强度上限=15.0, 调节速度=0.15,
                 静息抑制=1.0, 反馈抑制=0.12, 去抑抵消=0.2):
        self.宽度 = 宽度
        self.每段 = 每段
        self.门槛 = 门槛
        self.目标下限 = 目标下限
        self.目标上限 = 目标上限
        self.目标比例下限 = 目标比例下限
        self.目标比例上限 = 目标比例上限
        self.典型念头 = 0.0   # 跑起来自动记住念头典型大小（学习时统计）
        self.强度下限 = 强度下限
        self.强度上限 = 强度上限
        self.调节速度 = 调节速度
        self.静息抑制 = 静息抑制
        self.反馈抑制 = 反馈抑制
        self.去抑抵消 = 去抑抵消
        self.联想 = 连接表()   # 念头细胞 a → {后继念头细胞 b: 权重}（带定期遗忘）
        self.去抑 = 连接表()   # 念头细胞 a → {后继位点 s: 权重}（带定期遗忘）
        self.强度 = 强度初值  # 整体抑制强度（运行中动态调节）
        self.念头 = np.zeros(宽度, dtype=bool)

    def 连接数(self):
        """统计用：学过的联想连接条数"""
        return self.联想.条数()

    def 学习(self, 前念头, 后念头):
        """时序赫布：先激活的 前念头 → 后激活的 后念头（同对再现就加粗）"""
        self.联想.维护()   # 到达警戒线后定期整体衰减，防无限增长
        self.去抑.维护()
        前们 = np.nonzero(前念头)[0]
        后们 = np.nonzero(后念头)[0]
        if len(前们) == 0 or len(后们) == 0:
            return
        # 记住念头典型大小：目标区间跟着念头尺度走（念头大就宽、念头小就窄）
        if self.典型念头 <= 0.0:
            self.典型念头 = float(len(后们))
        else:
            self.典型念头 = 0.9 * self.典型念头 + 0.1 * float(len(后们))
        for a in 前们:
            a = int(a)
            for b in 后们:
                b = int(b)
                self.联想.学习(a, b)
            见过的位点 = set()
            for b in 后们:
                s = int(b) // self.每段
                if s in 见过的位点:
                    continue
                见过的位点.add(s)
                self.去抑.学习(a, s)

    def 驱动(self, 上念头):
        """当前念头 → 每个学过后继细胞收到的联想信号（没学过的细胞收 0）"""
        L = np.zeros(self.宽度)
        for a in np.nonzero(上念头)[0]:
            for b, w in self.联想.查(int(a)).items():
                L[b] += w
        return L

    def 门场(self, 上念头):
        """每个位点的净抑制：整体强度×(静息+局部反馈) − 去抑制门控，夹到 ≥ 0"""
        位点数 = (self.宽度 + self.每段 - 1) // self.每段
        反馈 = np.zeros(位点数)
        for a in np.nonzero(上念头)[0]:
            反馈[a // self.每段] += 1
        抑制场 = self.强度 * (self.静息抑制 + self.反馈抑制 * 反馈)
        去抑场 = np.zeros(位点数)
        for a in np.nonzero(上念头)[0]:
            for s, w in self.去抑.查(int(a)).items():
                去抑场[s] += w
        return np.maximum(0.0, 抑制场 - self.去抑抵消 * 去抑场)

    def 微步(self, 上念头, 外部信号=None):
        """内部放电一步 + 动态整体抑制当场收敛（上念头 → 下念头）

        联想投票 + 外部信号先按 门槛 + 本地净抑制 亮一轮；
        这一轮亮得比念头该有的规模多 → 抑制当场收紧，只留信号最强的
        目标范围上限个（不会一帧冒出几千个旧记忆）；
        亮得太少且确实有信号 → 抑制放松，多留几个。
        目标范围跟随念头典型大小自动伸缩：念头大就宽、念头小就窄，
        始终把激活数保持在"合适值"（既不少到叫不醒，也不多到乱成一锅）。"""
        L = self.驱动(上念头)
        if 外部信号 is not None:
            L = L + np.asarray(外部信号, dtype=float)
        门 = self.门场(上念头)
        位点 = np.arange(self.宽度) // self.每段
        下念头 = L >= self.门槛 + 门[位点]
        亮数 = int(下念头.sum())
        尝试过 = 外部信号 is not None or bool(L.any())

        # ---- 动态整体抑制：目标区间跟着念头典型大小走 ----
        目标下 = max(self.目标下限, int(round(self.典型念头 * self.目标比例下限)))
        目标上 = max(self.目标上限, int(round(self.典型念头 * self.目标比例上限)))
        if 亮数 > 目标上:
            # 太多了：抑制当场收紧，只留信号最强的 目标上 个
            强信号 = L[下念头]
            阈值 = np.partition(强信号, len(强信号) - 目标上)[len(强信号) - 目标上]
            下念头 = L >= max(阈值, 1.0)
            亮数 = int(下念头.sum())
            self.强度 = min(self.强度上限, self.强度 * (1.0 + self.调节速度))
        elif 亮数 < 目标下 and 尝试过:
            # 太少了：抑制放松，在确实有信号的细胞里多留几个
            信号 = L[L > 0]
            if len(信号) >= 目标下:
                阈值 = np.partition(信号, len(信号) - 目标下)[len(信号) - 目标下]
                下念头 = L >= max(阈值, 1e-9)
                亮数 = int(下念头.sum())
            self.强度 = max(self.强度下限, self.强度 * (1.0 - self.调节速度))
        self.念头 = 下念头
        return 下念头


class 专注闸门:
    """前额叶对外三通路的"专注闸门"：深度思考时自动关窗，对外时自动开窗

    抑制池与去抑制池（都加在前额叶神经网络和镜像返回线的通路上）：
      · 抑制神经元池：被内部念头活跃驱动 —— 念头在跑 = 深度思考 → 抑制变强
      · 去抑制神经元池：自发放电维持通路开放（听外界、回忆、动作是默认状态），
        抑制池强过它时通路才被压住（"去抑制神经元抑制住抑制神经元"）
      · 每条通路净开度 = 去抑活性 − 抑活性：压不住就全通，压住了就合闸
    三条通路：
      · 输入通路（外界三路 → 前额叶神经网络）：专注时压低 —— 外界信号叫不醒，
        深度思考不被打断
      · 回忆通路（镜像返回线等自动回忆）：专注时不主动回忆 —— 不想回忆时就不回忆
      · 运动通路（念头 → 运动区命令）：专注时只"想"不动 —— 闸开才把动作外发
    专注不是瞬间开关：念头一来，抑制要几个微步才压过自发放电；
    念头一停，通路逐步恢复（注意力转移需要时间）。
    """

    def __init__(self, 转变速度=0.35, 输入抑制率=0.95, 回忆抑制率=1.0, 运动抑制率=1.0):
        self.转变速度 = 转变速度
        self.输入抑制率 = 输入抑制率
        self.回忆抑制率 = 回忆抑制率
        self.运动抑制率 = 运动抑制率
        self.专注 = 0.0   # 当前专注强度：0 = 完全对外，1 = 完全在内部思考

    def 更新(self, 内部念头):
        """每个内部微步后调用：念头亮着 → 专注慢慢升到 1；念头空了 → 慢慢回 0"""
        目标 = 1.0 if 内部念头.sum() > 0 else 0.0
        self.专注 += self.转变速度 * (目标 - self.专注)
        if 目标 == 1.0 and 1.0 - self.专注 <= 0.001:
            self.专注 = 1.0   # 涨到头 = 完全专注（抑制池完全压过自发放电）
        elif 目标 == 0.0 and self.专注 <= 0.001:
            self.专注 = 0.0   # 回到底 = 完全对外

    def 抑制(self, 路):
        """某条通路当前的抑制量（0 = 全开，1 = 合闸）"""
        if 路 == "输入":
            return min(1.0, self.专注 * self.输入抑制率)
        if 路 == "回忆":
            return min(1.0, self.专注 * self.回忆抑制率)
        return min(1.0, self.专注 * self.运动抑制率)


