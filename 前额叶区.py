    for _ in range(5):
        联想3.学习(A, B)          # B：跟过 A 五次，记得最牢
    for k in range(40):          # 另外 40 个都只跟过一次 = 弱候选
        联想3.学习(A, 造码(3000 + k * 60))
    print("5.5 一次冒出太多候选 → 整体抑制自动收紧（只留记牢的 B，弱候选被压掉）:")
    for 轮 in range(1, 26):
        念头 = 联想3.微步(A)
        亮 = int(念头.sum())
        if 亮 <= 联想3.目标上限:
            print(f"    第 {轮} 轮: 亮 {亮} 个（只剩 B: {(念头 & B).sum()}/10）"
                  f" | 强度 {联想3.强度:.2f} → 稳定")
            break
        print(f"    第 {轮} 轮: 亮 {亮} 个（太多）| 强度 {联想3.强度:.2f}")

    # ---- 5.6 一个念头后面全是弱候选 → 收紧过头就叫不醒，自动放松（动态平衡）----
    联想4 = 前额叶联想区(输入数量)
    for k in range(40):
        联想4.学习(A, 造码(6000 + k * 60))
    print("5.6 弱候选太多叫不醒 → 整体抑制自动放松，松过头又冒太多 → 再收紧:（动态平衡震荡）")
    for 轮 in range(1, 25):
        念头 = 联想4.微步(A)
        亮 = int(念头.sum())
        print(f"    第 {轮} 轮: 亮 {亮} 个 | 强度 {联想4.强度:.2f}"
              + ("（太少了，放松）" if 亮 < 联想4.目标下限 else "")
              + ("（太多了，收紧）" if 亮 > 联想4.目标上限 else ""))

    # ===== 6) 专注闸门：抑制/去抑制神经元池 接在 前额叶神经网络 与 镜像返回线 的通路上 =====
    print("\n== 6) 专注闸门：深度思考时压住 外界/回忆/运动，停下后自动恢复 ==")

    def 一路状态():
        return (f"专注 {闸门.专注 * 100:.0f}%"
                f" | 外界通路净开 {100 - 闸门.抑制('输入') * 100:.0f}%"
                f" | 回忆通路净开 {100 - 闸门.抑制('回忆') * 100:.0f}%"
                f" | 运动通路净开 {100 - 闸门.抑制('运动') * 100:.0f}%")

    # 6.1 没在想事情时：去抑制池自发放电 → 窗全开（听外界、自动回忆、动手都是默认状态）
    print("6.1 初始（没念头，完全对外）:", 一路状态())

    # 6.2 念头一直亮着（反复想 A↔B 同一件事）→ 抑制池越压越强 → 专注慢慢升到 1
    联想环 = 前额叶联想区(输入数量)
    for _ in range(3):
        联想环.学习(A, B)
        联想环.学习(B, A)
    念头 = A
    for 轮 in range(1, 26):
        念头 = 联想环.微步(念头)
        闸门.更新(念头)
        if 轮 in (1, 5, 10, 15, 25):
            print(f"    思考第 {轮:2d} 个微步:", 一路状态())

    # 6.3 同一帧外界信号：对外时能进，专注后只剩 5% 透入 → 基本叫不醒
    视出, 听出, 运入 = 一帧随机经历()
    对外输出 = 前额网.前向传播(视出, 听出, 运入).astype(bool)
    衰减 = 闸门.抑制("输入")
    专注输出 = 前额网.前向传播(视出, 听出, 运入, 输入衰减=衰减).astype(bool)
    print(f"6.3 同一帧外界信号: 对外时前额输出 {int(对外输出.sum())} 个"
          f" → 专注时（外界净开 {100 - 衰减 * 100:.0f}%）只剩 {int(专注输出.sum())} 个")

    # 6.4 同一个念头：回忆通路（天生互惠返回线）合闸 → 不想回忆就真的不回忆
    样例输出 = next(o for o in 输出们 if o.sum() > 0)
    开提示 = 返回线.返回(样例输出)
    回忆抑制 = 闸门.抑制("回忆")
    关提示 = 返回线.返回(样例输出, 抑制量=回忆抑制)
    print(f"6.4 同一个念头: 对外时镜像线回忆提示 {int(开提示.sum())} 个"
          f" → 专注时 {int(关提示.sum())} 个（回忆通路全关）")

    # 6.5 运动通路（念头 → 运动输出区）本文件还没有外发实线，先看闸门开度：
    #     闸合上 = 光想不动手；闸打开 = 念头才发成动作（由运动输出区的反向网负责外发）
    print(f"6.5 运动通路: 专注时念头外发动作的闸门净开 {100 - 闸门.抑制('运动') * 100:.0f}%"
          f"（合闸 = 不想动就不动，深度思考不会被自己的动作打断）")

    # 6.6 念头停了 → 专注慢慢回落 → 三路逐渐恢复（注意力转移需要时间）
    print("6.6 念头停下，专注回落，通路恢复:")
    空念头 = np.zeros(输入数量, dtype=bool)
    for 轮 in range(1, 21):
        闸门.更新(空念头)
        if 轮 in (1, 5, 10, 15, 20):
            print(f"    停想第 {轮:2d} 个微步:", 一路状态())
