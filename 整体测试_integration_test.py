"""整体联调测试：持续随机输入，检查全链路是否有问题。

流程（每 0.1 秒一帧，时间由海马体共享时钟驱动）：
  1. 视觉区：随机外部信号 → 视觉输出（稀疏码）
  2. 听觉区：随机外部信号 → 听觉输出（稀疏码）
  3. 运动区：随机"乱动"信号 → 肌肉状态 + 命令模式；学运动反向网络
  4. 前额叶：三路(视输出 + 听输出 + 运动命令) → 前额输出
  5. 三个记忆区分别把本区输出模式按时间记下
每 10 帧检查一次：前向是否有零输出帧、运动反向召回质量、连接增长速度、每帧耗时。

注意：前额叶区的"回忆"现在由 海马索引 + 联想区 + 天生互惠返回线 承担，
不再带独立的"前额反向大表"，所以这里只检查运动反向网络。
三路宽度各自跟随 视觉前处理 / 听觉前处理 / 运动输出区 的输入层，改数字自动联动。
"""
import sys
import time
import numpy as np
import 海马体时间区_hippocampal_time as 时间区
import 视觉前处理_visual_preprocess as 视觉
import 听觉前处理_auditory_preprocess as 听觉
import 运动输出区_motor_output as 运动
import 前额叶区_prefrontal as 前额
import 视觉记忆区_visual_memory
import 听觉记忆区_auditory_memory
import 运动记忆区_motor_memory

np.random.seed(2026)

帧数 = int(sys.argv[1]) if len(sys.argv) > 1 else 50
每帧步数 = 时间区.时钟.每帧步数

视记 = 视觉记忆区.记忆区(视觉.网.输出层数量)
听记 = 听觉记忆区.记忆区(听觉.网.输出层数量)
运记 = 运动记忆区.记忆区(运动.网.输出层数量)
运动反向 = 运动.反向赫布网络(运动.特征神经元池(运动.对数))   # 文档原版全连

肌肉史 = []
命令史 = []
视零 = 听零 = 运零 = 前额零 = 0
总耗时 = 0.0

运动上限 = 运动.对数          # 肌肉侧每对恰激活一个，每帧肌肉状态数 = 对数

# 运动区用"婴儿式平滑乱动"驱动：每帧发力只小步变化（真实动作连续，
# 不会每帧随机跳到一个完全无关的姿势，那样只会让反向记忆互相淹没）
运动发力 = np.random.uniform(0.3, 0.7, size=运动.肌肉数)


def 检查(f, 上次连接, 上次帧):
    """用最近 10 帧检查运动反向网络"""
    lo = max(0, f - 9)
    命中 = 0
    for k in range(lo, f + 1):
        找回 = 运动反向.前向(命令史[k])
        命中 += int((找回 & 肌肉史[k]).sum())
    n = f - lo + 1
    连 = 运动反向.条数()
    新增帧数 = f - 上次帧
    增速 = (连 - 上次连接) / max(1, 新增帧数)
    print(f"[帧 {f + 1:>2}] 运动反向: 每帧平均找回重合 {命中 / n:.0f}/{运动上限}"
          f" | 连接数 {连:,} (+{增速:.0f}/帧)"
          f" | 前向零输出: 视{视零} 听{听零} 运{运零} 前额{前额零}")
    return 连, f


print("时间神经元数量:", 时间区.时钟.时间神经元数量,
      "| 一帧:", 时间区.时钟.每步秒数 * 每帧步数, "秒")
print("三路宽度(自动联动): 视觉", 视觉.网.输出层数量,
      "+ 听觉", 听觉.网.输出层数量,
      "+ 运动", 运动.网.输出层数量,
      "= 前额输入", 前额.输入数量)
print("=" * 100)

上次运动连 = 0
上次检查帧 = -1
for f in range(帧数):
    t0 = time.perf_counter()

    旧时间, 新时间 = 时间区.时钟.一帧()

    # ---- 1) 视觉：随机外部信号 ----
    视觉输出 = 视觉.网.前向传播(np.random.uniform(0, 1, 视觉.池.总数)).astype(bool)
    if 视觉输出.sum() == 0:
        视零 += 1

    # ---- 2) 听觉：随机外部信号 ----
    听觉输出 = 听觉.网.前向传播(np.random.uniform(0, 1, 听觉.池.总数)).astype(bool)
    if 听觉输出.sum() == 0:
        听零 += 1

    # ---- 3) 运动区：平滑乱动 → 肌肉状态 + 命令模式；学运动反向 ----
    运动发力 = np.clip(运动发力 + np.random.normal(0.0, 0.04, size=运动.肌肉数), 0.0, 1.0)
    运动.网.前向传播(运动.发力转信号(运动发力))
    肌肉状态 = 运动.池.激活.copy()
    运动命令 = 运动.网.普通层激活[-1].astype(bool)
    if 运动命令.sum() == 0:
        运零 += 1
    运动反向.学习一帧(肌肉状态, 运动命令)

    # ---- 4) 前额叶：三路输入(宽度可不同) → 输出 ----
    前额输出 = 前额.前额网.前向传播(视觉输出, 听觉输出, 运动命令).astype(bool)
    if 前额输出.sum() == 0:
        前额零 += 1

    # ---- 5) 三个记忆区按共享时间记下本区输出模式 ----
    视记.学习(旧时间, 新时间, 视觉输出)
    听记.学习(旧时间, 新时间, 听觉输出)
    运记.学习(旧时间, 新时间, 运动命令)

    肌肉史.append(肌肉状态)
    命令史.append(运动命令)

    总耗时 += time.perf_counter() - t0

    if (f + 1) % 10 == 0:
        上次运动连, 上次检查帧 = 检查(f, 上次运动连, 上次检查帧)

print("=" * 100)
print(f"总耗时: {总耗时:.2f} 秒（{帧数} 帧，平均每帧 {总耗时 / 帧数 * 1000:.1f} 毫秒）")
print(f"运动反向连接: {运动反向.条数():,} 条（每帧新增约 {运动反向.条数() / 帧数:.0f} 条）")
print(f"前向零输出累计: 视觉 {视零} 帧, 听觉 {听零} 帧, 运动 {运零} 帧, 前额叶 {前额零} 帧")
print("记忆区连接数: 视觉", len(视记.特征到时间) + sum(len(v) for v in 视记.时间到特征.values()),
      "听觉", len(听记.特征到时间) + sum(len(v) for v in 听记.时间到特征.values()),
      "运动", len(运记.特征到时间) + sum(len(v) for v in 运记.时间到特征.values()))

# ===== 额外测试：50 帧"没学过"的全新平滑动作，运动反向会不会退化 =====
重合 = 0
for _ in range(50):
    运动发力 = np.clip(运动发力 + np.random.normal(0.0, 0.04, size=运动.肌肉数), 0.0, 1.0)
    运动.网.前向传播(运动.发力转信号(运动发力))
    肌肉状态 = 运动.池.激活.copy()
    运动命令 = 运动.网.普通层激活[-1].astype(bool)
    运动回想 = 运动反向.前向(运动命令)
    重合 += int((运动回想 & 肌肉状态).sum())
print(f"没学过的全新平滑动作 50 帧：平均找回重合 {重合 / 50:.0f}/{运动上限}"
      f"（随机约 {运动上限 // 2}；越高说明反向越能泛化到新动作）")
