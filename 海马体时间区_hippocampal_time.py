import numpy as np


class 时间环:
    """海马体时间区：全系统共享的一条时间线

    时间神经元绕成一圈（像手串的珠子，首尾相连）；
    每走一格 = 0.05 秒（内部时间步）；
    一帧（外界信息传入一次）= 每帧步数 格 = 0.1 秒；
    绕一圈 = 时间神经元数量 × 每步秒数 = 24 小时。
    """

    def __init__(self, 时间神经元数量=1728000, 每步秒数=0.05, 每帧步数=2):
        self.时间神经元数量 = 时间神经元数量
        self.每步秒数 = 每步秒数
        self.每帧步数 = 每帧步数
        self.时间激活 = np.zeros(时间神经元数量, dtype=bool)
        self.当前时间 = 0
        self.时间激活[0] = True

    def 走一步(self):
        """内部时间步（0.05 秒）：当前熄灭，下一格激活，返回(旧时间, 新时间)"""
        旧时间 = self.当前时间
        新时间 = (旧时间 + 1) % self.时间神经元数量
        self.时间激活[旧时间] = False
        self.当前时间 = 新时间
        self.时间激活[新时间] = True
        return 旧时间, 新时间

    def 一帧(self):
        """外界每 0.1 秒来一帧：内部连走 每帧步数 步"""
        旧时间, 新时间 = 0, 0
        for _ in range(self.每帧步数):
            旧时间, 新时间 = self.走一步()
        return 旧时间, 新时间


# ===== 全系统共享的唯一时钟：所有记忆区都引用它 =====
时钟 = 时间环()


if __name__ == "__main__":
    print("时间神经元数量:", 时钟.时间神经元数量)
    print("一帧秒数:", 时钟.每步秒数 * 时钟.每帧步数)               # 0.1
    print("绕一圈小时:", 时钟.时间神经元数量 * 时钟.每步秒数 / 3600)  # 24

    旧时间, 新时间 = 时钟.走一步()
    print("走一步:", 旧时间, "→", 新时间)

    旧时间, 新时间 = 时钟.一帧()
    print("走一帧(2步):", 旧时间, "→", 新时间)