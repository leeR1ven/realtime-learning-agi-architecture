"""0.5G 版本 + 多姿态角动量自检"""
import numpy as np
import 身体 as B

def H_踝(身):
    st = B.读状态(身)
    角度 = st["角度"]; 角速 = st["角速"]
    关, 质心 = B.关节位置质心(角度)
    v关 = [np.zeros(2) for _ in range(4)]
    H = 0.0
    for i in range(3):
        ω = 角速[i]
        v关[i+1] = v关[i] + B.叉(ω, B.节表[i][1]*B.方向(角度[i]))
        v质 = v关[i] + B.叉(ω, B.节表[i][3]*B.方向(角度[i]))
        r = 质心[i] - 关[0]
        H += B.节表[i][2]*B.叉积y(r, v质) + B.节表[i][4]*ω
    return H

冲 = 24.0
for 姿态 in ([0,0,0], [0.15,0.1,-0.08], [-0.1,0.2,0.15]):
    身 = B.建身体(角度=姿态)
    B.加推力(身, 冲)
    t0 = 身["时间"]
    while 身["时间"] < t0 + 0.05:
        B.物理一步(身, np.zeros(3))
    st = B.读状态(身)
    C3 = B.关节位置质心(st["角度"])[1][2]
    力臂 = C3[1] - B.踝高
    print(f"姿态{姿态}: 期望H={冲*力臂:.2f} 实测H={H_踝(身):.2f} 比值={H_踝(身)/(冲*力臂):.3f}")