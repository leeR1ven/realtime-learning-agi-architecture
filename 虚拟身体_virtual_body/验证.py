"""验证.py —— 用数字验证"本能"是否成立（无图形窗口）

场景：
  1) 静站 8 秒
  2) 推力扫描(前推/后推) —— 纯踝+髋，不跳步
  3) 蹲姿起身
  4) 跳步恢复 —— 推力过大时允许"起跳-悬空-落地换支点"(真实迈步物理)

运行: python 验证.py 全部
      python 验证.py 站立 / 推力 / 起身 / 跳步
"""
import sys
import numpy as np
import 身体 as B
import 感官本能 as S

控制周期 = 0.005          # 200 Hz：每周期 10 个物理子步
秒数 = 8.0
角度转度 = 57.2958
跳步冷却 = 0.45           # 两次起跳之间的最短间隔(秒)


def 跑回合(初始角度, 冲量=0.0, 最长秒=秒数, 报告间隔=0, 允许跳=False):
    """带本能跑一回合。返回(状态,发力,倒没倒,原因,最大前倾,想迈步,跳数,位移)"""
    身 = B.建身体(角度=初始角度)
    S.重置本能()
    if 冲量:
        B.加推力(身, 冲量)
    最大前倾 = 0.0
    想迈步 = 0
    跳数 = 0
    位移 = 0.0
    上次跳时间 = -9.0
    步 = 0
    while 身["时间"] < 最长秒:
        状态 = B.读状态(身)
        最大前倾 = max(最大前倾, abs(状态["前倾"]))
        if 身["模式"] == "空":
            扭矩 = S.空中本能(状态)
        else:
            _, 扭矩, 迈 = S.本能连接(状态)
            if 迈:
                想迈步 += 1
            if (允许跳 and 迈 and 身["时间"] - 上次跳时间 > 跳步冷却
                    and (abs(状态["前倾速度"]) > 1.8 or abs(状态["前倾"]) > 0.25)):
                # 起跳瞬间立刻切空中本能，避免把站立扭矩带进空中打乱姿态
                扭矩 = S.空中本能(状态)
                B.起跳(身, S.跳升速)
                上次跳时间 = 身["时间"]
                跳数 += 1
        # 每个子步实时看模式：空中一旦落地就结束本控制周期，
        # 下一周期立刻换回站立本能，绝不在落地后继续做空中积分。
        for _ in range(10):
            if 身["模式"] == "空":
                if B.悬空一步(身, 扭矩):
                    break
            else:
                B.物理一步(身, 扭矩)
        位移 = 身["脚x"]
        步 += 1
        状态 = B.读状态(身)
        if 报告间隔 and 步 % 报告间隔 == 0:
            print(f"  t={状态['时间']:.2f} 模式={身['模式']} 前倾={状态['前倾']*角度转度:6.1f}° "
                  f"膝弯={状态['膝弯']*角度转度:5.1f}° 跳={跳数}")
        if 身["模式"] == "站":
            倒, 因 = B.摔倒了吗(状态)
            if 倒:
                return 状态, np.zeros(0), True, 因, 最大前倾, 想迈步, 跳数, 位移
    return 状态, np.zeros(0), False, "", 最大前倾, 想迈步, 跳数, 位移


def 场景1_静站():
    print("场景1: 直立静站 8 秒")
    状态, _, 倒, 因, 最大前倾, 想迈, 跳, 移 = 跑回合([0.0, 0.0, 0.0], 报告间隔=200)
    print(f"  结果: {'摔倒(' + 因 + ')' if 倒 else '站住'} | "
          f"最大前倾 {最大前倾*角度转度:.2f}° | 结束前倾 {状态['前倾']*角度转度:.2f}°")
    return not 倒


def 场景2_推力():
    print("场景2: 推力扫描(不跳步，纯踝+髋+阻尼)")
    print("  冲量(N·s)   结果          最大前倾     结束前倾")
    冲量表 = [4, 8, 12, 16, 20, 24, 28, 32, 36, 40]
    for 冲 in 冲量表:
        for 方向 in (1.0, -1.0):
            状态, _, 倒, 因, 最大前倾, 想迈, 跳, 移 = 跑回合([0.0, 0.0, 0.0],
                                                      冲量=冲 * 方向)
            print(f"  {冲*方向:+6.1f}      "
                  f"{('摔(' + 因 + ')') if 倒 else '站住':<14s} "
                  f"{最大前倾*角度转度:8.2f}°    {状态['前倾']*角度转度:8.2f}°")
    return True


def 场景3_起身():
    print("场景3: 深蹲起步（膝弯约57°，髋屈约42°），看本能能否自己站起来站稳")
    状态, _, 倒, 因, 最大前倾, 想迈, 跳, 移 = 跑回合([0.35, -0.64, 0.10],
                                             最长秒=12.0, 报告间隔=400)
    print(f"  结果: {'摔倒(' + 因 + ')' if 倒 else '站住'} | "
          f"结束: 前倾 {状态['前倾']*角度转度:.1f}° 膝弯 {状态['膝弯']*角度转度:.1f}° "
          f"髋屈 {状态['髋屈']*角度转度:.1f}°")
    return not 倒


def 场景4_跳步():
    print("场景4: 推力扫描(允许真实跳步换支点)")
    print("  冲量(N·s)   结果          最大前倾     结束前倾     跳数/位移")
    冲量表 = [16, 20, 24, 28, 32, 36, 40]
    for 冲 in 冲量表:
        for 方向 in (1.0, -1.0):
            状态, _, 倒, 因, 最大前倾, 想迈, 跳, 移 = 跑回合([0.0, 0.0, 0.0],
                                                      冲量=冲 * 方向, 允许跳=True)
            print(f"  {冲*方向:+6.1f}      "
                  f"{('摔(' + 因 + ')') if 倒 else '站住':<14s} "
                  f"{最大前倾*角度转度:8.2f}°    {状态['前倾']*角度转度:8.2f}°   "
                  f"{跳}次/{移:+.2f}m")
    return True


if __name__ == "__main__":
    模式 = sys.argv[1] if len(sys.argv) > 1 else "全部"
    if 模式 in ("全部", "站立"):
        场景1_静站()
    if 模式 in ("全部", "推力"):
        场景2_推力()
    if 模式 in ("全部", "起身"):
        场景3_起身()
    if 模式 in ("全部", "跳步"):
        场景4_跳步()