"""_调试8.py —— 基础检查: 无推力原地垂直起跳, 落地后能否站住; 以及落地姿态展开
"""
import numpy as np
import 身体 as B
import 感官本能 as S

for 升速 in (1.0, 1.6, 2.0):
    S.跳升速 = 升速
    S.重置本能()
    身 = B.建身体()
    st = B.读状态(身)
    B.起跳(身, 升速)
    身["基速"][0] = 0.0
    t落 = None
    while 身["时间"] < 3.0 and t落 is None:
        st = B.读状态(身)
        扭矩 = S.空中本能(st) if 身["模式"] == "空" else S.本能连接(st)[1]
        for _ in range(10):
            if 身["模式"] == "空":
                if B.悬空一步(身, 扭矩):
                    t落 = 身["时间"]
                    break
            else:
                B.物理一步(身, 扭矩)
    print(f"升速={升速}: 空中时长={t落:.3f}s", end="")
    倒 = False
    for _ in range(600):   # 落地后再看 3 秒
        st = B.读状态(身)
        扭矩 = S.本能连接(st)[1]
        for _ in range(10):
            B.物理一步(身, 扭矩)
        st = B.读状态(身)
        倒, 因 = B.摔倒了吗(st)
        if 倒:
            break
    a = st["角度"]
    print(f" 落地后: {'摔倒('+因+')' if 倒 else '站住'} 踝={a[0]*57.3:+.0f}° 膝={a[1]*57.3:+.0f}° 髋={a[2]*57.3:+.0f}° 前倾={st['前倾']*57.3:+.1f}° 髋高={st['髋高度']:.2f}")