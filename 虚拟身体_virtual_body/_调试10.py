"""物理自检: 推力是否守恒(F*dt = m*dv)"""
import numpy as np
import 身体 as B

for 冲 in (5.0, 10.0, 24.0):
    身 = B.建身体()
    B.加推力(身, 冲)   # 持续 0.05s
    # 无肌肉无阻尼推 0.05s
    import 感官本能 as S
    v0 = B.读状态(身)["质心速度"][0]
    推前时间 = 身["时间"]
    while 身["时间"] < 推前时间 + 0.05:
        B.物理一步(身, np.zeros(3))
    st = B.读状态(身)
    dv = st["质心速度"][0] - v0
    m = sum(s[2] for s in B.节表)
    print(f"冲量={冲}: 期望dv={冲/m:.3f} 实测dv={dv:.3f} 踝角={st['踝角']*57.3:.1f}° 前倾={st['前倾']*57.3:.1f}°")
# 再测一次 无推力 静立带PD 1s 后 COM 速度应≈0
身 = B.建身体()
S.重置本能()
while 身["时间"] < 1.0:
    _, 扭, _ = S.本能连接(B.读状态(身))
    for _ in range(10):
        B.物理一步(身, 扭)
st = B.读状态(身)
print("静立1s后: vcom=", st["质心速度"].round(4), " 前倾=", round(st["前倾"],4))