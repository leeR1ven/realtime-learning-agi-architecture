"""感官本能.py —— 感官特征神经元池 + 固定"本能连接" + 运动神经元池(肌肉发力)

神经元风格沿用项目：每个量用 每档对数 对神经元做温度计码，
信号进池 -> 每对竞争出激活 -> 解码回档数(0~每档) -> 发力。

感官通道全部是 0~1 单向通道（正/反拆成两个通道，像肌肉屈/伸成对）。
运动池：6 块肌肉，每块 每档对数 对，解码 = 发力档 0~每档。
本能连接 = 固定增益表 + 线性读出，不学习不训练。肌肉有发力滞后(时间常数)。
"""
import numpy as np
重力 = 9.81               # 与 身体.py 的重力常量一致

每档对数 = 32
控制周期 = 0.005          # 一次本能连接的计算周期(秒)，与验证.py 一致
上次净扭矩 = np.zeros(3)  # 肌肉扭矩惯性(模拟肌肉不能瞬间满力)

# 感官通道: 名字, 满刻度(物理量折到 1.0 的刻度)
感官通道表 = [
    ("前倾", 0.9),        # 质心相对踝支点前倾角(弧度)
    ("后仰", 0.9),
    ("前倾速度", 2.5),
    ("后仰速度", 2.5),
    ("膝弯", 1.6),
    ("伸膝速度", 3.0),
    ("屈膝速度", 3.0),
    ("髋屈", 1.3),
    ("髋后仰", 1.0),
    ("屈髋速度", 3.0),
    ("伸髋速度", 3.0),
    ("躯干前倾", 0.9),
    ("躯干后仰", 0.9),
]
通道名 = [c[0] for c in 感官通道表]
感官对数 = len(感官通道表) * 每档对数


class 感官池:
    """与特征神经元池同构：信号数组 + 每对二选一激活"""

    def __init__(self):
        self.对数 = 感官对数
        self.总数 = self.对数 * 2
        self.信号 = np.zeros(self.总数)
        self.激活 = np.zeros(self.总数, dtype=bool)

    def 更新所有对(self):
        正 = self.信号[0::2]
        反 = self.信号[1::2]
        正赢 = 正 >= 反
        self.激活[0::2] = 正赢
        self.激活[1::2] = ~正赢
        self.信号[:] = 0.0


# 肌肉: 名字, 满发力时的关节扭矩(牛·米，含方向)
肌肉表 = [
    ("腓肠肌·跖屈", -240),
    ("胫前肌·背屈", 240),
    ("股四头肌·伸膝", 340),
    ("腘绳肌·屈膝", -240),
    ("臀肌·伸髋", -300),
    ("髂腰肌·屈髋", 120),
]
肌肉数 = len(肌肉表)
运动对数 = 肌肉数 * 每档对数
对关节 = [(0, 1), (3, 2), (4, 5)]   # 每关节(负向肌下标, 正向肌下标)


class 运动池:
    def __init__(self):
        self.对数 = 运动对数
        self.总数 = self.对数 * 2
        self.信号 = np.zeros(self.总数)
        self.激活 = np.zeros(self.总数, dtype=bool)

    def 更新所有对(self):
        正 = self.信号[0::2]
        反 = self.信号[1::2]
        正赢 = 正 >= 反
        self.激活[0::2] = 正赢
        self.激活[1::2] = ~正赢
        self.信号[:] = 0.0


def 量转信号(通道数, 值列表):
    """一组 0~1 数值 -> 温度计信号(档级=round(值*每档))，可直接写进池.信号"""
    级 = np.clip(np.rint(np.asarray(值列表, dtype=float) * 每档对数).astype(int),
                 0, 每档对数)
    信号 = np.zeros(通道数 * 每档对数 * 2)
    for c in range(通道数):
        起 = c * 每档对数
        for j in range(每档对数):
            对 = 起 + j
            if j < 级[c]:
                信号[2 * 对] = 1.0
            else:
                信号[2 * 对 + 1] = 1.0
    return 信号


def 解码档数(池, 通道数):
    """激活 -> 每通道 0~每档 档数数组"""
    正 = 池.激活[0::2]
    return 正.reshape(通道数, 每档对数).sum(axis=1)


# ==================== 本能连接（固定增益，不学习） ====================
# 三档本能，从弱到强：
#  1) 踝：质心前倾 -> 腓肠肌跖屈把身体拉回；后仰 -> 胫前肌背屈（始终小修正）
#  2) 髋/膝：躯干竖直(髋)、膝盖保持微弯不锁死(膝)，随时能弯能伸
#  3) 迈步：前倾/后仰超过阈值，说明光靠踝+髋救不回来 -> 朝倾倒方向"伸腿落一步"，
#    把脚挪到质心前方再站稳。前倾就往前提脚，后仰就往后挪脚，方向与倾倒相反。
肌肉时间常数 = 0.03      # 肌肉从发令到出力的滞后(秒)
迈步阈值 = 0.16          # 质心前倾超过约 9° 就输出迈步意图(是否起跳由速度再决定)
迈步冷却 = 0.15          # 迈完一步后要等多久才能再迈(秒)
迈步提前 = 0.5           # 落脚点超前量(相对"倾倒速度自然停止点"的倍数)
最大步长 = 0.7           # 一步最多挪多远(米)
最小步长 = 0.25          # 一步最少挪多远(米)
迈步冷却时间 = 0.0       # 剩余冷却秒数(回合内由 重置本能 清零)

# PD 增益
Kp踝 = 200.0
Kd踝 = 90.0
Kp膝 = 800.0
Kd膝 = 120.0
膝目标弯 = 0.05          # 站立时膝盖微弯弧度，避免膝反张锁死
Kp髋直 = 200.0           # 躯干竖直刚度
Kd髋直 = 35.0
Kp髋策 = 0.0             # 前倾耦合髋策略: 暂时关掉(腿前扫时它会帮倒忙)
Kd髋策 = 0.0
K韧带 = 900.0            # 膝反张(<0°)时的"韧带"刚度：无源结构，不算肌肉
C韧带 = 200.0            # 膝反张区内的速度阻尼(双向，防止回弹振荡)

# 每关节肌肉: (负向肌肉下标, 正向肌肉下标, 负向满扭矩, 正向满扭矩)
关节肌肉表 = [(0, 1, -240.0, 240.0),   # 踝: 腓肠肌(跖屈) / 胫前肌(背屈)
             (3, 2, -240.0, 340.0),    # 膝: 腘绳肌(屈膝) / 股四头肌(伸膝)
             (4, 5, -300.0, 120.0)]    # 髋: 臀肌(伸髋) / 髂腰肌(屈髋)


def 本能连接(状态):
    """感官状态 -> (发力档[6], 净扭矩[踝,膝,髋], 迈步距离米)
    每 控制周期 调一次；内部记住肌肉滞后与迈步冷却。"""
    global 迈步冷却时间

    前倾 = 状态["前倾"]
    前倾速度 = 状态["前倾速度"]
    膝弯 = 状态["膝弯"]
    膝弯速度 = 状态["膝弯速度"]
    躯干前倾 = 状态["躯干前倾"]
    躯干角速 = 状态["躯干角速"]

    # --- 目标扭矩(PD)，先按肌肉极限压住 ---
    目标踝 = -(Kp踝 * 前倾 + Kd踝 * 前倾速度)
    目标膝 = Kp膝 * (膝弯 - 膝目标弯) + Kd膝 * 膝弯速度
    目标髋 = -(Kp髋直 * 躯干前倾 + Kd髋直 * 躯干角速) - \
             (Kp髋策 * 前倾 + Kd髋策 * 前倾速度)
    目标肌 = np.clip(np.array([目标踝, 目标膝, 目标髋]),
                     np.array([j[2] for j in 关节肌肉表]),
                     np.array([j[3] for j in 关节肌肉表]))
    # 韧带扭矩(无源，不被肌肉极限限制)：膝弯越过 0° 后渐进顶回 + 阻尼
    韧带扭矩 = np.zeros(3)
    if 膝弯 < 0.0:
        韧带扭矩[1] = K韧带 * 膝弯 + C韧带 * 膝弯速度
    目标 = 目标肌 + 韧带扭矩

    # --- 换算成六块肌肉的发力需求(0~1)，转成温度计档数 ---
    需求 = np.zeros(肌肉数)
    for j, (负肌, 正肌, 负满, 正满) in enumerate(关节肌肉表):
        if 目标肌[j] < 0:
            需求[负肌] = 目标肌[j] / 负满
        else:
            需求[正肌] = 目标肌[j] / 正满
    需求 = np.clip(需求, 0.0, 1.0)
    发力档 = np.rint(需求 * 每档对数).astype(int)

    # --- 肌肉滞后：净扭矩向目标慢慢靠，模拟肌肉不能瞬间满力 ---
    系数 = min(1.0, 控制周期 / 肌肉时间常数)
    净扭矩 = 上次净扭矩 + (目标 - 上次净扭矩) * 系数
    上次净扭矩[:] = 净扭矩

    # --- 迈步本能：倾得太狠就朝倾倒方向伸腿，落脚点 = 质心预测停点 ---
    迈步距离 = 0.0
    迈步冷却时间 -= 控制周期
    if 迈步冷却时间 <= 0.0:
        质心x = 状态["质心相对脚x"]
        高 = max(状态["质心高度"], 0.3)
        # 用"整体倾倒速度"(前倾角速度×高度)而不是关节甩动速度算落脚点
        整体速度 = 状态["前倾速度"] * 高
        预测步 = 质心x + 整体速度 * 迈步提前 * (高 / 重力) ** 0.5
        if 前倾 > 迈步阈值:
            迈步距离 = float(np.clip(预测步, 最小步长, 最大步长))
            迈步冷却时间 = 迈步冷却
        elif 前倾 < -迈步阈值:
            迈步距离 = float(np.clip(预测步, -最大步长, -最小步长))
            迈步冷却时间 = 迈步冷却
    return 发力档, 净扭矩, 迈步距离


def 重置本能():
    """每回合开始调用：清零肌肉滞后与迈步冷却。"""
    global 迈步冷却时间
    global 空中冷却时间
    上次净扭矩[:] = 0.0
    迈步冷却时间 = 0.0
    空中冷却时间 = 0.0


# ============ 空中(迈步跳跃)本能 ============
# 方向感知: 前倒 -> 空中把脚摆到质心前面(整条腿后仰、躯干竖直)；
#           后倒 -> 镜像，脚摆到质心后面。落地后交回站立本能。
空中踝Kp = 150.0
空中踝Kd = 20.0
空中膝Kp = 120.0
空中膝Kd = 25.0
空中髋Kp = 260.0
空中髋Kd = 50.0
踝空前目标 = -0.12    # 前倒: 小腿略后仰 -> 脚落在质心前(身体后仰接住)
踝空后目标 = +0.12    # 后倒: 小腿略前倾 -> 脚落在质心后(身体前倾接住)
膝空目标 = 0.30       # 空中略收膝(落地缓冲，太深会被误判坐倒)
跳升速 = 1.8          # 起跳的竖直升速(米/秒)
空中冷却时间 = 0.0     # 两次起跳之间的冷却(秒)


def 空中本能(状态):
    """脚离地时使用：躯干竖直 + 收膝 + 朝倾倒反方向摆脚。落地后交回站立本能。"""
    踝目标 = 踝空前目标 if 状态["前倾"] >= 0 else 踝空后目标
    τ0 = 空中踝Kp * (踝目标 - 状态["踝角"]) - 空中踝Kd * 状态["角速"][0]
    τ1 = 空中膝Kp * (状态["膝弯"] - 膝空目标) + 空中膝Kd * 状态["膝弯速度"]
    τ2 = -(空中髋Kp * 状态["躯干前倾"] + 空中髋Kd * 状态["躯干角速"])
    return np.clip(np.array([τ0, τ1, τ2]),
                   np.array([j[2] for j in 关节肌肉表]),
                   np.array([j[3] for j in 关节肌肉表]))


