import numpy as np
import 身体 as B

def 总能(身):
    st = B.读状态(身)
    角度 = st["角度"]
    v关 = [np.zeros(2) for _ in range(4)]
    v关[0] = 身["基速"] if 身["模式"] == "空" else np.zeros(2)
    E = 0.0
    for i in range(3):
        关, 质心 = B.关节位置质心(角度, 0.0, 0.0)
    v关 = [np.zeros(2) for _ in range(4)]
    v关[0] = np.array(身["基速"]) if 身["模式"] == "空" else np.zeros(2)
    for i in range(3):
        ω = 身["角速"][i]
        v关[i + 1] = v关[i] + B.叉(ω, B.节表[i][1] * B.方向(角度[i]))
        v质 = v关[i] + B.叉(ω, B.节表[i][3] * B.方向(角度[i]))
        E += 0.5 * B.节表[i][2] * (v质 @ v质) + 0.5 * B.节表[i][4] * ω * ω
        E += B.节表[i][2] * B.重力 * (质心[i][1])
    if 身["模式"] == "空":
        E += 19.0 * B.重力 * (身["基位"][1] - B.踝高)
    return E

# 测试1: 直立原地起跳(竖直升速1.0)，空中不给扭矩，应回到原位站住
身 = B.建身体()
B.起跳(身, 1.0)
E0 = 总能(身)
print("起跳后 模式=", 身["模式"], " 基速=", 身["基速"].round(3))
步 = 0
while 身["模式"] == "空" and 步 < 5000:
    B.悬空一步(身, np.zeros(3))
    步 += 1
    if 步 % 200 == 0:
        print(f"  t={身['时间']:.3f} 基位z={身['基位'][1]:.4f} 基速y={身['基速'][1]:.2f}")
print("落地后 模式=", 身["模式"], " 步数=", 步, " 角度=", 身["角度"].round(4),
      " 角速=", 身["角速"].round(4))
print("能量 起飞", round(E0, 3), "落地", round(总能(身), 3))

