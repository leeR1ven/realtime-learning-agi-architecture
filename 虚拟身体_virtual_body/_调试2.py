import numpy as np
import 身体 as B

# 测试1: 把肌肉扭矩设成 h（重力补偿解），qdd 应该=0
身 = B.建身体(角度=[0.1, 0.05, -0.02], 角速=[0.0]*3)
h = B.递推(身["角度"], 身["角速"], np.zeros(3), True)
G = np.array([[1.,-1.,0.],[0.,1.,-1.],[0.,0.,1.]])
M = B.质量矩阵(身["角度"])
Mg = G@M; hg = G@h
qdd = np.linalg.solve(Mg, G@h - hg)   # 若逻辑对，应为0
print("测试1 重力补偿: qdd =", qdd)

# 测试2: 自由落体能量漂移 vs 步长
for dt in (0.002, 0.0005, 0.0001):
    身2 = B.建身体(角度=[0.15]*3)
    B.阻尼[:] = [0,0,0]
    def 总能():
        st = B.读状态(身2)
        关2, 质心2 = B.关节位置质心(st["角度"])
        E = 0.0; v关 = [np.zeros(2) for _ in range(4)]
        for i in range(3):
            ω = st["角速"][i]
            v质 = v关[i] + B.叉(ω, B.节表[i][3]*B.方向(st["角度"][i]))
            v关[i+1] = v关[i] + B.叉(ω, B.节表[i][1]*B.方向(st["角度"][i]))
            E += 0.5*B.节表[i][2]*(v质@v质)+0.5*B.节表[i][4]*ω*ω+B.节表[i][2]*B.重力*质心2[i][1]
        return E
    E0 = 总能()
    n = int(1.0/dt)
    for _ in range(n):
        B.物理一步(身2, np.zeros(3), dt)
    E1 = 总能()
    print(f"测试2 dt={dt}: 1秒后漂移 {abs(E1-E0)/abs(E0)*100:.3f}%  E0={E0:.1f} E1={E1:.1f}")

