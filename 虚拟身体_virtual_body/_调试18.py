"""_调试18.py —— 踝肌肉力量上限(±70) 扫描: 不跳 vs 跳"""
import numpy as np
import 身体 as B
import 感官本能 as S

S.踝上限 = 70.0
S.关节肌肉表[0] = (0, 1, -S.踝上限, S.踝上限)
秒数 = 4.0
跳步冷却 = 0.35

def 跑(冲, 允许跳):
    S.重置本能()
    身 = B.建身体()
    B.加推力(身, 冲)
    上次跳 = -9.0
    跳数 = 0
    最大 = 0.0
    while 身["时间"] < 秒数:
        st = B.读状态(身)
        最大 = max(最大, abs(st["前倾"]))
        if 身["模式"] == "空":
            扭矩 = S.空中本能(st)
        else:
            _, 扭矩, 迈 = S.本能连接(st)
            if (允许跳 and 迈 and 身["时间"] - 上次跳 > 跳步冷却
                    and (abs(st["前倾速度"]) > 1.8 or abs(st["前倾"]) > 0.25)):
                扭矩 = S.空中本能(st)
                B.起跳(身, S.跳升速)
                上次跳 = 身["时间"]
                跳数 += 1
        for _ in range(10):
            if 身["模式"] == "空":
                if B.悬空一步(身, 扭矩):
                    break
            else:
                B.物理一步(身, 扭矩)
        st = B.读状态(身)
        if 身["模式"] == "站":
            倒, 因 = B.摔倒了吗(st)
            if 倒:
                return f"摔({因})", 最大, 跳数
    return "站住", 最大, 跳数

# 先静态检查
S.重置本能()
身 = B.建身体()
while 身["时间"] < 8.0:
    st = B.读状态(身)
    _, 扭矩, _ = S.本能连接(st)
    for _ in range(10):
        B.物理一步(身, 扭矩)
st = B.读状态(身)
print(f"静站8s: {'站住' if not B.摔倒了吗(st)[0] else '摔了'} 前倾={np.degrees(st['前倾']):.2f}°")
print("冲量     不跳                        允许跳")
for 冲 in (12.0, 16.0, 20.0, 24.0, 28.0, 32.0, 40.0):
    for 方向 in (1.0, -1.0):
        r1 = 跑(冲*方向, False)
        r2 = 跑(冲*方向, True)
        print(f"{冲*方向:+6.0f}  {r1[0]:<16s} 最大{np.degrees(r1[1]):5.1f}°  |  "
              f"{r2[0]:<16s} 最大{np.degrees(r2[1]):5.1f}° 跳{r2[2]}")