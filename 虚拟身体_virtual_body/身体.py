# ===================== 悬空(真实迈步/跳跃)物理 =====================
# 迈步分三段：起跳(脚离地) -> 悬空(质心抛物线，肌肉摆腿) -> 落地(换新支点)。
# 落地按"脚点完全非弹性"处理：脚速度清零，绕落地点的角动量守恒 -> 求新角速度。

def 起跳(身体, 升速):
    """站立 -> 悬空：保持姿态/角速度；水平速度用整体倾倒速度(限幅)，竖直给升速。"""
    st = 读状态(身体)
    vx = float(st["前倾速度"] * st["质心高度"])
    vx = float(np.clip(vx, -3.0, 3.0))
    身体["基速"] = np.array([vx, 升速])
    身体["基位"] = np.array([float(身体.get("基x", 0.0)), 踝高])
    身体["模式"] = "空"


def 悬空递推(角度, 角速, 角加速度, 基加速度):
    """给定基座平动加速度时，三节链需要的关节扭矩 + 质心加速度。"""
    关, 质心 = 关节位置质心(角度, 0.0, 0.0)
    线加关 = [np.zeros(2) for _ in range(4)]
    线加质 = [np.zeros(2) for _ in range(3)]
    线加关[0] = np.asarray(基加速度, dtype=float)
    for i in range(3):
        ω = 角速[i]
        α = 角加速度[i]
        r关 = 节表[i][1] * 方向(角度[i])
        r质 = 节表[i][3] * 方向(角度[i])
        线加关[i + 1] = 线加关[i] + 叉(α, r关) + 叉(ω, 叉(ω, r关))
        线加质[i] = 线加关[i] + 叉(α, r质) + 叉(ω, 叉(ω, r质))
    总质量 = sum(节表[i][2] for i in range(3))
    a_com = sum(节表[i][2] * 线加质[i] for i in range(3)) / 总质量
    τ = np.zeros(3)
    F子 = np.zeros(2)
    gv = np.array([0.0, -重力])
    for i in range(2, -1, -1):
        _, 长, 质量, 距, 惯量 = 节表[i]
        F父 = 质量 * (线加质[i] - gv) + F子
        τ[i] = (惯量 * 角加速度[i]
                - 叉积y(关[i] - 质心[i], F父)
                + 叉积y(关[i + 1] - 质心[i], F子))
        F子 = F父
    return τ, a_com


def 悬空一步(身体, 关节扭矩, dt=None):
    """悬空积分一子步。触地则完成 落地 并返回 True。"""
    if dt is None:
        dt = 子步长
    角度 = 身体["角度"]
    角速 = 身体["角速"]
    基位 = 身体["基位"]
    基速 = 身体["基速"]
    gvec = np.array([0.0, -重力])

    def 残差(u5):
        τ, a_com = 悬空递推(角度, 角速, u5[:3], u5[3:5])
        return np.concatenate([τ - np.asarray(关节扭矩, dtype=float),
                               a_com - gvec])

    u0 = np.zeros(5)
    r0 = 残差(u0)
    J = np.zeros((5, 5))
    for k in range(5):
        e = np.zeros(5)
        e[k] = 1.0
        J[:, k] = 残差(e) - r0
    u = np.linalg.solve(J, -r0)
    角速 += u[:3] * dt
    角度 += 角速 * dt
    基速 += u[3:5] * dt
    基位 += 基速 * dt
    身体["时间"] += dt
    if 基位[1] <= 踝高 and 基速[1] <= 0.0:
        基位[1] = 踝高
        落地(身体)
        return True
    return False


def 自由动能矩阵(角度):
    """自由链(基座平动2自由度+3关节)的 5x5 动能矩阵 K：T = ½ uᵀ K u。"""
    def T(u):
        v关 = [np.zeros(2) for _ in range(4)]
        v关[0] = u[:2]
        t = 0.0
        for i in range(3):
            ω = u[2 + i]
            v关[i + 1] = v关[i] + 叉(ω, 节表[i][1] * 方向(角度[i]))
            v质 = v关[i] + 叉(ω, 节表[i][3] * 方向(角度[i]))
            t += 0.5 * 节表[i][2] * (v质 @ v质) + 0.5 * 节表[i][4] * ω * ω
        return t
    K = np.zeros((5, 5))
    for i in range(5):
        ei = np.zeros(5)
        ei[i] = 1.0
        for j in range(i, 5):
            ej = np.zeros(5)
            ej[j] = 1.0
            K[i, j] = K[j, i] = T(ei + ej) - T(ei) - T(ej)
    return K


def 落地(身体):
    """触地瞬间：脚点完全非弹性(速度清零)，冲量-动量方程 -> 新关节角速度。"""
    角度 = 身体["角度"]
    u前 = np.concatenate([身体["基速"], 身体["角速"]])
    K = 自由动能矩阵(角度)
    # 接触约束：基座点速度=0，雅可比 Jc = [I2, 0]
    Jc = np.zeros((2, 5))
    Jc[0, 0] = Jc[1, 1] = 1.0
    A = Jc @ np.linalg.solve(K, Jc.T)
    lam = -np.linalg.solve(A, Jc @ u前)
    u后 = u前 + np.linalg.solve(K, Jc.T @ lam)
    身体["角速"] = u后[2:5]
    身体["基速"][:] = 0.0
    身体["脚x"] = float(身体["基位"][0])
    身体["基x"] = float(身体["基位"][0])
    身体["模式"] = "站"
