import numpy as np
import 身体 as B
import 感官本能 as S

冲 = float(input().strip()) if False else 24.0
身 = B.建身体()
S.重置本能()
B.加推力(身, 冲)
上次 = -9.0
次 = 0
while 身["时间"] < 3.0:
    st = B.读状态(身)
    if 身["模式"] == "空":
        扭矩 = S.空中本能(st)
    else:
        _, 扭矩, 迈 = S.本能连接(st)
        if 迈 and 身["时间"] - 上次 > 0.45:
            上次 = 身["时间"]
            B.起跳(身, S.跳升速)
            print(f"t={身['时间']:.3f} 起跳! 基速={身['基速'].round(2)} 前倾={st['前倾']*57.3:.1f}°")
    for _ in range(10):
        if 身["模式"] == "空":
            B.悬空一步(身, 扭矩)
        else:
            B.物理一步(身, 扭矩)
    st = B.读状态(身)
    次 += 1
    if 次 % 20 == 0:
        a = st["角度"]
        print(f"t={身['时间']:.3f} 模式={身['模式']} 基位=({身['基位'][0]:.2f},{身['基位'][1]:.2f}) "
              f"踝={a[0]*57.3:5.1f} 膝={a[1]*57.3:5.1f} 髋={a[2]*57.3:5.1f} "
              f"前倾={st['前倾']*57.3:6.1f} 髋高={st['髋高度']:.2f}")
    if 身["模式"] == "站":
        倒, 因 = B.摔倒了吗(st)
        if 倒:
            print("摔倒:", 因, " t=", round(身["时间"], 3))
            break
