"""_调试9b.py —— 同 _调试9 但二次起跳收紧: 只有明显再倒才跳
用法: python _调试9b.py [冲量] [升速]
"""
import sys
import numpy as np
import 身体 as B
import 感官本能 as S

冲 = float(sys.argv[1]) if len(sys.argv) > 1 else 24.0
升速 = float(sys.argv[2]) if len(sys.argv) > 2 else 2.0

S.踝空目标 = -0.12
S.膝空目标 = 0.30
S.空中踝Kp = 150.0
S.空中踝Kd = 20.0
S.空中膝Kp = 120.0
S.跳升速 = 升速

S.重置本能()
身 = B.建身体()
B.加推力(身, 冲)
上次跳 = -9.0
跳数 = 0
次 = 0
print(f"推力={冲:+.0f} 升速={升速}")
while 身["时间"] < 4.0:
    st = B.读状态(身)
    if 身["模式"] == "空":
        扭矩 = S.空中本能(st)
    else:
        _, 扭矩, 迈 = S.本能连接(st)
        if 身["时间"] - 上次跳 > 0.30 and 身["时间"] > 0.005:
            if 跳数 == 0:
                可跳 = (st["前倾"] > 0.02 and st["前倾速度"] > 0.7) or st["前倾"] > 0.10
            else:
                可跳 = st["前倾"] > 0.12 and st["前倾速度"] > 1.5
            if 可跳:
                st = B.读状态(身)
                扭矩 = S.空中本能(st)
                B.起跳(身, 升速)
                身["基速"][0] = float(np.clip(st["质心速度"][0], -3.0, 3.0))
                上次跳 = 身["时间"]
                跳数 += 1
                a = st["角度"]; o = st["角速"]
                print(f"[跳{跳数}] t={身['时间']:.3f} 前倾={st['前倾']*57.3:+.1f}° ω={st['前倾速度']:+.2f} "
                      f"踝={a[0]*57.3:+.0f}° 膝={a[1]*57.3:+.0f}° 髋={a[2]*57.3:+.0f}° "
                      f"髋ω={o[2]:+.2f} 基速={身['基速'].round(2)}")
    for _ in range(10):
        if 身["模式"] == "空":
            if B.悬空一步(身, 扭矩):
                st = B.读状态(身)
                a = st["角度"]; o = st["角速"]
                print(f"[落地{跳数}] t={身['时间']:.3f} 脚x={身['脚x']:+.3f} rel={st['质心相对脚x']:+.3f} "
                      f"踝={a[0]*57.3:+.0f}° 膝={a[1]*57.3:+.0f}° 髋={a[2]*57.3:+.0f}° "
                      f"前倾={st['前倾']*57.3:+.1f}° 角速={o.round(2)} 髋高={st['髋高度']:.2f}")
                break
        else:
            B.物理一步(身, 扭矩)
    st = B.读状态(身)
    次 += 1
    if 次 % 4 == 0 and 身["时间"] - 上次跳 > 0.01:
        a = st["角度"]; o = st["角速"]
        print(f"t={身['时间']:.3f} {身['模式']} rel={st['质心相对脚x']:+.3f} "
              f"踝={a[0]*57.3:+5.1f} 膝={a[1]*57.3:+5.1f} 髋={a[2]*57.3:+5.1f} "
              f"前倾={st['前倾']*57.3:+6.1f} 髋高={st['髋高度']:.2f} 髋ω={o[2]:+.2f}")
    if 身["模式"] == "站":
        倒, 因 = B.摔倒了吗(st)
        if 倒:
            print("摔倒:", 因, " t=", round(身["时间"], 3))
            break
else:
    print("4 秒内站稳")