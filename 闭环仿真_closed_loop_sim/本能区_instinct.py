"""出生本能区：感受区到运动区的固定直接投射，不经过前额叶，也不参与赫布学习。

分工（避免抢走学习信号）
  皮肤触觉只在"已经接触"时驱动动作（脱困反射，不预判）：
    · 前方被顶住 → 后退，并朝两侧更空旷的一边转向；
    · 左侧被顶住 → 右转并轻推，沿墙面滑出；右侧对称；
    · 后方被顶住 → 向前脱离。
  痛觉超过阈值 → 本能哭喊（发出的音调可被自己听见，进入后续学习闭环）。
  预判式"绕开上次撞过的墙"仍由疼痛赫布学习出的危险权重提供，
  因此本能不会让身体在没撞过之前就学会躲墙。

  前额叶对动作的接管在 Brain 的动作选择处统一实现：学到且置信度高的
  声音→动作映射会把整套本能/反射分量按 (1 - 2*置信度) 衰减，
  即"随着学习，本能逐渐让位给前额叶"。
"""
from __future__ import annotations

import numpy as np


class 本能区:
    """固定的出生本能连接；动作顺序与脑一致：[静息,前进,后退,左转,右转]。

    纯加权固定连接：接触(4) → 动作(5) 的固定矩阵 + 前方开度选边 +
    痛觉 → 哭喊的固定阈值。全部在出生时定死，无任何可塑参数。
    """

    # 接触方向顺序与 world 一致：[前, 后, 左, 右]。
    接触直行 = np.array([
        [0.00, 0.00, 1.00, 0.00, 0.00],  # 前触 → 后退
        [0.00, 0.85, 0.00, 0.00, 0.00],  # 后触 → 前进脱离
        [0.00, 0.30, 0.05, 0.00, 0.90],  # 左触 → 右转 + 前推滑脱
        [0.00, 0.30, 0.05, 0.90, 0.00],  # 右触 → 左转 + 前推滑脱
    ], dtype=float)

    选边增益 = 0.8     # 前触时"两侧开度差"转成转向的幅度
    开度标尺 = 2.5     # 左右平均射线距离差归一化的尺度（米）
    哭阈值 = 0.45      # 解码后痛觉达到该值才哭
    哭冷却 = 30        # 哭一次后至少间隔的帧数
    哭音调 = 3         # 用最高音调带(880Hz)当哭喊，可被自己听见
    哭响度 = 0.2

    def __init__(self):
        self.接触直行 = np.asarray(self.接触直行, dtype=float)
        self.选边增益 = float(self.选边增益)
        self.开度标尺 = float(self.开度标尺)
        self.哭阈值 = float(self.哭阈值)
        self.哭冷却 = int(self.哭冷却)
        self.哭音调 = int(self.哭音调)
        self.哭响度 = float(self.哭响度)

    def fixed_arrays(self) -> dict[str, np.ndarray]:
        """出生定死的全部参数，随存档校验/融合。"""
        return {'contact': self.接触直行.copy(),
                'open_gain': np.array([self.选边增益, self.开度标尺]),
                'cry': np.array([self.哭阈值, self.哭冷却, self.哭音调, self.哭响度])}

    def 驱动(self, 接触, 距离, 痛觉, 哭冷却):
        """输入接触/五束距离/痛觉/哭冷却，返回(动作分量, 是否哭)。

        分量会加进本能/反射分数，之后在动作选择处整体受
        "前额叶接管衰减"调节；哭是一次性的固定痛觉→发声反射。
        """
        接触 = np.asarray(接触, dtype=float)
        if 接触.shape != (4,) or not np.isfinite(接触).all() or np.any((接触 < 0) | (接触 > 1)):
            raise ValueError('本能区需要四方向0~1接触信号: [前,后,左,右]')
        距离 = np.asarray(距离, dtype=float)
        if 距离.shape != (5,) or not np.isfinite(距离).all() or np.any(距离 < 0):
            raise ValueError('本能区需要五束非负射线距离')
        痛觉 = float(痛觉)
        if not np.isfinite(痛觉) or 痛觉 < 0:
            raise ValueError('本能区需要非负痛觉')
        分量 = 接触 @ self.接触直行
        # 前触脱困：偏向两侧中更空旷的一边（只选边，不做预判）。
        if 接触[0] > 0:
            右开 = (距离[0] + 距离[1]) * 0.5
            左开 = (距离[3] + 距离[4]) * 0.5
            偏向 = float(np.clip((右开 - 左开) / self.开度标尺, -1.0, 1.0)) * 接触[0]
            分量[3] += max(-偏向, 0.0) * self.选边增益   # 左侧更开 → 左转
            分量[4] += max(偏向, 0.0) * self.选边增益    # 右侧更开 → 右转
        哭 = bool(痛觉 >= self.哭阈值 and 哭冷却 <= 0)
        return 分量, 哭


if __name__ == '__main__':
    from itertools import product
    # 自检：每个接触方向的胜出动作、选边方向、哭喊门槛都是出生定值。
    s = 本能区()
    mid = np.full(5, 3.0)
    期望 = {(1, 0, 0, 0): 2, (0, 1, 0, 0): 1, (0, 0, 1, 0): 4, (0, 0, 0, 1): 3}
    for 掩码 in product((0.0, 1.0), repeat=4):
        if 掩码.count(1.0) != 1:
            continue
        分量, 哭 = s.驱动(np.array(掩码), mid, 0.0, 0)
        assert not 哭 and int(np.argmax(分量)) == 期望[掩码], (掩码, 分量)
    右开 = s.驱动(np.array([1., 0, 0, 0]), np.array([4.9, 4.9, 2., 2., 2.]), 0.0, 0)[0]
    左开 = s.驱动(np.array([1., 0, 0, 0]), np.array([2., 2., 2., 4.9, 4.9]), 0.0, 0)[0]
    assert 右开[4] > 右开[3] and 左开[3] > 左开[4], (右开, 左开)
    _, 哭 = s.驱动(np.zeros(4), mid, 0.8, 0);   assert 哭
    _, 哭 = s.驱动(np.zeros(4), mid, 0.1, 0);   assert not 哭
    _, 哭 = s.驱动(np.zeros(4), mid, 0.8, 5);   assert not 哭
    assert len(s.fixed_arrays()) == 3
    print('本能区自检 PASS：接触退缩/侧滑选向/前方开度选边/痛觉哭喊/出生定值')