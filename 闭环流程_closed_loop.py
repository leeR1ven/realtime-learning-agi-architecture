"""闭环流程_closed_loop.py —— 全部件"接入清单 + 闭环联测"

之前分文件自检都能跑，但有几个部件只在前额叶区的 __main__ 自检里跑过，
没有接进"整体测试_integration_test.py"那条全流程，等于"做了但没接上"：
    海马索引.锁定时间 / 记忆区.回忆 / 前额叶联想区(抑制·去抑制·动态稳态)
    / 专注闸门(抑制池 vs 去抑制池) / 天生互惠返回线

本文件把它们全部接到同一条闭环里再跑一遍，每段打印实测数字，
本身也就是一张"部件使用清单"。只读使用已有文件，不改任何一行。

用法：python 闭环流程_closed_loop.py [经历帧数，默认 40]
"""
import sys
import time
import numpy as np

import 海马体时间区_hippocampal_time as 时间区
import 视觉前处理_visual_preprocess as 视觉
import 听觉前处理_auditory_preprocess as 听觉
import 运动输出区_motor_output as 运动
import 前额叶区_prefrontal as 前额
import 视觉记忆区_visual_memory
import 听觉记忆区_auditory_memory
import 运动记忆区_motor_memory

np.random.seed(2026)

帧数 = int(sys.argv[1]) if len(sys.argv) > 1 else 40
每帧步数 = 时间区.时钟.每帧步数


def 造码(起点, 数量=10):
    """自检用的小念头（10 个细胞连在一起），只用于演示专注闸门动态"""
    码 = np.zeros(前额.输入数量, dtype=bool)
    码[起点:起点 + 数量] = True
    return 码


def 读时间内容(记忆, 时间):
    """某个时间神经元当时连着的特征：权重>=1 就算亮（一次学会，永不模糊）"""
    模式 = np.zeros(记忆.总数, dtype=bool)
    for 编号, w in 记忆.时间到特征.查(int(时间)).items():
        if w >= 1:
            模式[编号] = True
    return 模式


def 记忆区条数(记忆):
    return 记忆.特征到时间.条数() + 记忆.时间到特征.条数()


def 使用清单():
    print("=" * 100)
    print("使用清单：下面每个部件都会在本文件里真正跑起来")
    print(" 1. 视觉/听觉前处理正向网   ：随机外界信号 -> 稀疏输出        （在用）")
    print(" 2. 运动输出区正向网         ：发力温度计 -> 命令码           （在用）")
    print(" 3. 运动反向赫布网络         ：命令码 -> 肌肉 反向召回        （在用）")
    print(" 4. 三个记忆区.学习          ：按共享时间写时序记忆           （在用）")
    print(" 5. 海马索引.学习/锁定时间   ：前额念头 <-> 时刻              （本次接入）")
    print(" 6. 记忆区.回忆              ：特征 -> 时间链连续回放         （本次接入）")
    print(" 7. 前额叶联想区             ：念头链 + 抑制/去抑制 + 动态稳态（本次接入）")
    print(" 8. 专注闸门                 ：抑制池/去抑制池 压三通路       （本次接入）")
    print(" 9. 天生互惠返回线           ：固定连线、不学习、永远可用     （本次接入）")
    print("10. 权重连接管理             ：上述赫布连接内置定期遗忘       （在用）")
    print("=" * 100)


def 主流程():
    使用清单()
    t总 = time.perf_counter()

    视记 = 视觉记忆区.记忆区(前额.视宽)
    听记 = 听觉记忆区.记忆区(前额.听宽)
    运记 = 运动记忆区.记忆区(前额.运宽)
    索引 = 前额.海马索引()
    联想 = 前额.前额叶联想区(前额.输入数量, 门槛=300)  # 念头几百细胞，门槛按念头尺度调高
    闸门 = 前额.专注闸门()
    返回线 = 前额.返回线
    运动反向 = 运动.反向赫布网络(运动.特征神经元池(运动.对数))

    print("三路宽度(自动联动): 视觉", 前额.视宽, "+ 听觉", 前额.听宽,
          "+ 运动", 前额.运宽, "= 前额", 前额.输入数量)

    # ============ 第一阶段：真实经历 ============
    print("\n== 1) 经历写入：三区 -> 前额念头 -> 海马索引 + 记忆区 + 运动反向 ==")
    运动发力 = np.random.uniform(0.3, 0.7, size=运动.肌肉数)
    经历 = []
    视零 = 听零 = 运零 = 前额零 = 0
    t1 = time.perf_counter()
    for f in range(帧数):
        视出 = 视觉.网.前向传播(np.random.uniform(0, 1, 视觉.池.总数)).astype(bool)
        听出 = 听觉.网.前向传播(np.random.uniform(0, 1, 听觉.池.总数)).astype(bool)
        运动发力 = np.clip(运动发力 + np.random.normal(0.0, 0.04, size=运动.肌肉数), 0.0, 1.0)
        运动.网.前向传播(运动.发力转信号(运动发力))
        肌肉状态 = 运动.池.激活.copy()
        运动命令 = 运动.网.普通层激活[-1].astype(bool).copy()
        念头 = 前额.前额网.前向传播(视出, 听出, 运动命令).astype(bool).copy()
        视零 += int(视出.sum() == 0)
        听零 += int(听出.sum() == 0)
        运零 += int(运动命令.sum() == 0)
        前额零 += int(念头.sum() == 0)

        运动反向.学习一帧(肌肉状态, 运动命令)   # 命令码 -> 肌肉 的反向路

        起点 = 时间区.时钟.当前时间
        for s in range(每帧步数):
            旧, 新 = 时间区.时钟.走一步()
            if s == 0 and 念头.sum() > 0:
                索引.学习(旧, 念头)             # 念头 <-> 帧开头时间细胞
            视记.学习(旧, 新, 视出)
            听记.学习(旧, 新, 听出)
            运记.学习(旧, 新, 运动命令)
        经历.append(dict(视出=视出, 听出=听出, 命令=运动命令, 肌肉=肌肉状态,
                          念头=念头, 起点=起点))

    print(f"经历 {帧数} 帧用时 {time.perf_counter() - t1:.1f} 秒")
    print(f"前向零输出: 视{视零} 听{听零} 运{运零} 前额{前额零} 帧")
    print(f"记忆连接(时间<->特征): 视 {记忆区条数(视记):,} | "
          f"听 {记忆区条数(听记):,} | 运 {记忆区条数(运记):,}")
    print(f"海马索引连接: {索引.连接数():,} | 运动反向已学: {运动反向.条数():,} 条")

    # ============ 第二阶段：联想区学念头链（经验一遍 + 睡眠回放两遍） ============
    print("\n== 2) 前额联想区：念头链 经验1遍 + 睡眠回放2遍（重复记牢） ==")
    对们 = [(f, 经历[f]["念头"], 经历[f + 1]["念头"])
            for f in range(帧数 - 1)
            if 经历[f]["念头"].sum() > 0 and 经历[f + 1]["念头"].sum() > 0]
    t2 = time.perf_counter()
    for _ in range(3):
        for _, 前, 后 in 对们:
            联想.学习(前, 后)      # 时序赫布 + 抑制/去抑制，方向：先念头 -> 后念头
    print(f"念头对 {len(对们)} 对，回放3遍用时 {time.perf_counter() - t2:.1f} 秒")
    print(f"联想连接 {联想.连接数():,} 条 | 去抑门控 {联想.去抑.条数():,} 条")

    # ============ 第三阶段：念头链回想 ============
    print("\n== 3) 联想区回想：给上一个念头，能不能想起下一个念头 ==")
    print("（联想动态强度在每个查询前归位，模拟一次次独立回想）")
    取样 = 对们[:: max(1, len(对们) // 10)][:10]
    命中们, 全们, 多余们 = [], [], []
    for f, 前, 后 in 取样:
        联想.强度 = 1.0
        想起 = 联想.微步(前)
        命中 = int((想起 & 后).sum())
        全 = int(后.sum())
        命中们.append(命中)
        全们.append(全)
        多余们.append(int(想起.sum()) - 命中)
    if 命中们:
        print(f"  想下一个念头: 平均命中 {np.mean(命中们):.0f}/{int(np.mean(全们))}"
              f"（随机约 {np.mean(全们) * np.mean(全们) / 前额.输入数量:.1f}）"
              f" | 平均多余 {np.mean(多余们):.0f} 个/帧")
        print(f"  单帧明细: 命中 {命中们[:5]} / 全 {全们[:5]} / 多余 {多余们[:5]}")

    # ============ 第四阶段：海马索引 + 记忆区补全 ============
    print("\n== 4) 海马索引锁定时间 -> 三个记忆区补全那一刻的内容 ==")
    锁定们 = [r for r in 经历 if r["念头"].sum() > 0]
    锁对 = 漏锁 = 错锁 = 0
    统计 = {名: {"命中": 0, "原数": 0, "多余": 0} for 名 in ("视", "听", "运")}
    真们 = {"视": lambda r: r["视出"], "听": lambda r: r["听出"],
            "运": lambda r: r["命令"]}
    记们 = {"视": 视记, "听": 听记, "运": 运记}
    for r in 锁定们:
        t, 票数 = 索引.锁定胜出(r["念头"])
        if t is None:
            漏锁 += 1
            continue
        if t == r["起点"]:
            锁对 += 1
        else:
            错锁 += 1
        for 名 in ("视", "听", "运"):
            真 = 真们[名](r)
            内容 = 读时间内容(记们[名], t)
            统计[名]["命中"] += int((内容 & 真).sum())
            统计[名]["原数"] += int(真.sum())
            统计[名]["多余"] += int((内容 & ~真).sum())
    print(f"  时间锁定: {锁对}/{len(锁定们)} 帧完全正确（漏锁 {漏锁}，错锁 {错锁}）")
    for 名 in ("视", "听", "运"):
        s = 统计[名]
        print(f"  补全-{名}: 命中 {s['命中']}/{s['原数']} = "
              f"{s['命中'] / max(1, s['原数']) * 100:.1f}% | 多余 {s['多余']} 个（0=不掺假）")

    # ============ 第五阶段：记忆区.回忆 特征 -> 时间链连续回放 ============
    print("\n== 5) 记忆区.回忆：给一个特征，沿时间链连续回放后续帧 ==")
    回放统计 = {}
    for 名, 记忆 in (("视", 视记), ("听", 听记), ("运", 运记)):
        回放统计[名] = {"下一帧命中": 0, "下一帧全": 0, "能回放": 0, "试": 0}
        真 = 真们[名]
        for f in range(帧数 - 1):
            真前, 真后 = 真(经历[f]), 真(经历[f + 1])
            if 真前.sum() == 0 or 真后.sum() == 0:
                continue
            播放 = 记忆.回忆(真前, 步数=3)
            回放统计[名]["试"] += 1
            if not 播放:
                continue
            回放统计[名]["能回放"] += 1
            # 播放[0] 通常是当前帧自己，播放[1] 才是下一帧
            if len(播放) >= 2:
                下一帧特征 = 播放[1][1]
                回放统计[名]["下一帧命中"] += int((下一帧特征 & 真后).sum())
                回放统计[名]["下一帧全"] += int(真后.sum())
        s = 回放统计[名]
        if s["试"]:
            print(f"  {名}区: 试 {s['试']} 次, 能沿链回放 {s['能回放']} 次, "
                  f"下一帧命中 {s['下一帧命中']}/{s['下一帧全']} = "
                  f"{s['下一帧命中'] / max(1, s['下一帧全']) * 100:.1f}%")

    # ============ 第六阶段：念头 -> 联想 -> 锁时 -> 补全 端到端 ============
    print("\n== 6) 端到端：念头 -> 联想想起下一个念头 -> 海马锁时刻 -> 记忆区补全 ==")
    端锁对 = 端漏 = 0
    端命中 = {名: 0 for 名 in ("视", "听", "运")}
    端原 = {名: 0 for 名 in ("视", "听", "运")}
    for f, 前, _ in 取样:
        联想.强度 = 1.0
        想起 = 联想.微步(前)
        t, _ = 索引.锁定胜出(想起)
        后r = 经历[f + 1]
        if t is None or t != 后r["起点"]:
            端漏 += 1
            continue
        端锁对 += 1
        for 名 in ("视", "听", "运"):
            真 = 真们[名](后r)
            内容 = 读时间内容(记们[名], t)
            端命中[名] += int((内容 & 真).sum())
            端原[名] += int(真.sum())
    print(f"  联想想起的念头能正确锁到下一时刻: {端锁对}/{len(取样)}")
    for 名 in ("视", "听", "运"):
        print(f"  补全-{名}: 命中 {端命中[名]}/{端原[名]} = "
              f"{端命中[名] / max(1, 端原[名]) * 100:.1f}%")

    # ============ 第七阶段：天生互惠返回线（固定、不学习、全新念头也返回） ============
    print("\n== 7) 天生互惠返回线：旧念头 + 全新念头，固定连线直接回送提示 ==")

    def 返回线一次(视出, 听出, 命令):
        前额.前额网.前向传播(视出, 听出, 命令)
        提示 = 返回线.返回(前额.前额网.普通层激活[-1].astype(bool))
        扩散 = 前额.前额网.输入激活
        拼图 = np.concatenate([视出, 听出, 命令])
        return 提示, 扩散, 拼图

    def 打印返回线(名字, 帧们):
        覆盖, 精度, 数量, 零返 = [], [], [], 0
        for 视出, 听出, 命令 in 帧们:
            提示, 扩散, 拼图 = 返回线一次(视出, 听出, 命令)
            数量.append(int(提示.sum()))
            if not 提示.any():
                零返 += 1
                continue
            覆盖.append(float((提示 & 扩散).sum()) / 扩散.sum())
            精度.append(float((提示 & 拼图).sum()) / 提示.sum())
        if not 数量:
            return
        print(f"  {名字}: 提示平均点亮 {np.mean(数量):.0f} 个"
              f" | 覆盖真实扩散输入 {np.mean(覆盖) * 100:.1f}%"
              f" | 提示里含真亮点 {np.mean(精度) * 100:.1f}% | 零返回 {零返} 帧")

    旧帧们 = [(r["视出"], r["听出"], r["命令"]) for r in 锁定们[:10]]
    打印返回线("学过的经历(10帧)", 旧帧们)
    新帧们 = []
    for _ in range(10):
        视出 = 视觉.网.前向传播(np.random.uniform(0, 1, 视觉.池.总数)).astype(bool)
        听出 = 听觉.网.前向传播(np.random.uniform(0, 1, 听觉.池.总数)).astype(bool)
        运动发力 = np.clip(运动发力 + np.random.normal(0.0, 0.04, size=运动.肌肉数), 0.0, 1.0)
        运动.网.前向传播(运动.发力转信号(运动发力))
        命令 = 运动.网.普通层激活[-1].astype(bool)
        新帧们.append((视出, 听出, 命令))
    打印返回线("全新念头(10帧, 没学过)", 新帧们)

    # ============ 第八阶段：专注闸门（抑制池 vs 去抑制池） ============
    print("\n== 8) 专注闸门：想事情时抑制池压住 外界/回忆/运动，停想后恢复 ==")

    def 一路状态():
        return (f"专注 {闸门.专注 * 100:.0f}%"
                f" | 外界净开 {100 - 闸门.抑制('输入') * 100:.0f}%"
                f" | 回忆净开 {100 - 闸门.抑制('回忆') * 100:.0f}%"
                f" | 运动净开 {100 - 闸门.抑制('运动') * 100:.0f}%")

    print("  8.1 初始（没念头）:", 一路状态())

    A = 造码(100)
    B = 造码(300)
    联想环 = 前额.前额叶联想区(前额.输入数量, 门槛=2.0)  # 自检小念头(10细胞)用低门槛
    for _ in range(3):
        联想环.学习(A, B)
        联想环.学习(B, A)
    念头 = A
    for 轮 in range(1, 26):
        念头 = 联想环.微步(念头)
        闸门.更新(念头)
        if 轮 in (1, 5, 10, 25):
            print(f"    8.2 思考第 {轮:2d} 个微步:", 一路状态())

    r = 锁定们[0]
    对外输出 = 前额.前额网.前向传播(r["视出"], r["听出"], r["命令"]).astype(bool)
    衰减 = 闸门.抑制("输入")
    专注输出 = 前额.前额网.前向传播(r["视出"], r["听出"], r["命令"],
                                   输入衰减=衰减).astype(bool)
    print(f"  8.3 同一帧外界信号: 对外时前额输出 {int(对外输出.sum())} 个"
          f" -> 专注时（外界净开 {100 - 衰减 * 100:.0f}%）"
          f"只剩 {int(专注输出.sum())} 个")

    开提示 = 返回线.返回(r["念头"])
    关提示 = 返回线.返回(r["念头"], 抑制量=闸门.抑制("回忆"))
    print(f"  8.4 同一个念头: 回忆通路开时提示 {int(开提示.sum())} 个"
          f" -> 专注合闸后 {int(关提示.sum())} 个")

    运动抑制 = 闸门.抑制("运动")
    print(f"  8.5 运动通路: 专注时净开 {100 - 运动抑制 * 100:.0f}%"
          f"（合闸 = 光想不动手）")

    空念头 = np.zeros(前额.输入数量, dtype=bool)
    for 轮 in range(1, 21):
        闸门.更新(空念头)
        if 轮 in (1, 5, 10, 20):
            print(f"    8.6 停想第 {轮:2d} 个微步:", 一路状态())

    # ============ 汇总 ============
    print("\n" + "=" * 100)
    print(f"总用时 {time.perf_counter() - t总:.1f} 秒")
    print(f"正向零输出: 视{视零} 听{听零} 运{运零} 前额{前额零} / {帧数} 帧")
    print(f"记忆区连接: 视 {记忆区条数(视记):,} | 听 {记忆区条数(听记):,} | "
          f"运 {记忆区条数(运记):,}（带定期遗忘，不无限涨）")
    print(f"海马索引 {索引.连接数():,} | 联想 {联想.连接数():,} | "
          f"去抑门控 {联想.去抑.条数():,} | 运动反向 {运动反向.条数():,}")
    print("全部 10 类部件已在本文件里接入并跑通。")
    print("=" * 100)


if __name__ == "__main__":
    主流程()