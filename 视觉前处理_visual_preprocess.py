import numpy as np

class 特征神经元池:
    """numpy 版：所有神经元共用两个数组，速度比对象版快几十到几百倍"""

    def __init__(self, 对数):
        self.对数 = 对数
        self.总数 = 对数 * 2
        self.信号 = np.zeros(self.总数)              # 每个神经元的信号
        self.激活 = np.zeros(self.总数, dtype=bool)  # 每个神经元是否激活

    def 接收信号(self, 编号, 值):
        self.信号[编号] += 值

    def 更新所有对(self):
        正信号 = self.信号[0::2]   # 偶数下标 = 正神经元
        反信号 = self.信号[1::2]   # 奇数下标 = 反神经元
        正赢 = 正信号 >= 反信号    # 平局时正神经元赢
        self.激活[0::2] = 正赢
        self.激活[1::2] = ~正赢
        self.信号[:] = 0.0         # 清空本轮信号


class 神经网络:
    """局部连接版：每层神经元只连上一层附近的神经元（首尾成环）。

    最后一层可选用“归一化放电”（出生时自动校准，不用手调阈值）：
      每帧先算出整层每个细胞的加权和，按 全层均值 + α×全层标准差 放电，
      平均每帧亮几个由 输出目标亮数 决定，想改大/改小只改一个数字。
      最后一层用多宽的局部感受野由 输出感受野 决定（默认沿用 连接半径）。
    输出目标亮数 = 0 时完全退回旧版：所有层都用固定 阈值初值。
    """

    def __init__(self, 输入层, 层数, 连接半径=10,
                 权重范围=0.1, 阈值初值=0.5,
                 输出感受野=None, 输出目标亮数=0, 校准帧数=8):
        self.输入层 = 输入层
        self.对数 = 输入层.对数
        self.层数 = 层数
        self.半径 = 连接半径
        self.每层数 = 输入层.总数
        self.输出层数量 = self.每层数  # 最后一层神经元数量（记忆区靠它同步）
        self.输出感受野 = 连接半径 if 输出感受野 is None else 输出感受野
        self.输出目标亮数 = 输出目标亮数
        self.归一化输出 = 输出目标亮数 > 0
        self.输出α = 0.0

        self.来源 = []
        self.权重 = []
        self.阈值 = [np.full(self.每层数, 阈值初值) for _ in range(层数 - 1)]
        self.普通层激活 = [np.zeros(self.每层数, dtype=bool) for _ in range(层数 - 1)]

        for k in range(层数 - 1):
            # 最后一层且开了“归一化放电”→ 用加宽的 输出感受野；其它层用 连接半径
            用半径 = self.输出感受野 if (self.归一化输出 and k == 层数 - 2) else 连接半径
            连接数 = 2 * 用半径 + 1   # 每个神经元连几个邻居
            # 目标神经元 j 连上一层 j-半径 ~ j+半径，取模使首尾相接成环
            偏移 = np.arange(-用半径, 用半径 + 1)
            目标 = np.arange(self.每层数)
            来源 = (目标[:, None] + 偏移[None, :]) % self.每层数
            权重 = np.random.uniform(0, 权重范围, size=(self.每层数, 连接数))
            self.来源.append(来源)
            self.权重.append(权重)

        if self.归一化输出:
            self.输出α = self._校准输出α(输出目标亮数, 校准帧数)

    def _校准输出α(self, 目标亮数, 帧数):
        """出生时用随机输入试跑最后一层：找 α，使平均亮数 ≈ 目标亮数"""
        末层 = self.层数 - 2
        票们 = []
        for _ in range(帧数):
            self.输入层.信号[:] = np.random.uniform(0.0, 1.0, size=self.每层数)
            self.输入层.更新所有对()
            当前 = self.输入层.激活.astype(float)
            for k in range(末层):
                加权和 = (self.权重[k] * 当前[self.来源[k]]).sum(axis=1)
                当前 = (加权和 >= self.阈值[k]).astype(float)
            票们.append((self.权重[末层] * 当前[self.来源[末层]]).sum(axis=1))

        def 平均亮数(a):
            数 = 0.0
            for 票 in 票们:
                均值 = 票.mean(); 差 = 票.std() + 1e-9
                数 += float((票 >= 均值 + a * 差).sum())
            return 数 / len(票们)

        低, 高 = -3.0, 15.0
        for _ in range(16):
            中 = (低 + 高) / 2
            if 平均亮数(中) > 目标亮数:
                低 = 中
            else:
                高 = 中
        return (低 + 高) / 2

    def 前向传播(self, 输入信号):
        self.输入层.信号[:] = 输入信号
        self.输入层.更新所有对()
        当前激活 = self.输入层.激活.astype(float)

        for k in range(self.层数 - 1):
            加权和 = (self.权重[k] * 当前激活[self.来源[k]]).sum(axis=1)
            if self.归一化输出 and k == self.层数 - 2:
                # 最后一层：整层归一化放电（平均亮数 ≈ 输出目标亮数）
                均值 = 加权和.mean(); 差 = 加权和.std() + 1e-9
                当前激活 = 加权和 >= 均值 + self.输出α * 差
            else:
                当前激活 = 加权和 >= self.阈值[k]   # 神经元自己的放电门槛
            self.普通层激活[k] = 当前激活
            当前激活 = 当前激活.astype(float)

        return 当前激活


