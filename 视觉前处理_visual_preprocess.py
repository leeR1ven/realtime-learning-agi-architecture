# 视觉输入布局：想改分辨率 / 亮度档数，只改下面这一块数字
# ============================================================
大像素行数 = 24     # 画面竖向分成几格（马赛克格数）
大像素列数 = 16     # 画面横向分成几格（马赛克格数）
通道数 = 3          # R, G, B 三个通道
每档对数 = 10       # 每个通道用几对神经元 = 几档亮度（10 对 = 0~10 共 11 级）
层数 = 3
连接半径 = 10
权重范围 = 0.1
阈值初值 = 0.6
输出感受野 = 80    # 最后一层每个细胞看环上 ±输出感受野（越大越“看全局”，代价是变慢）
输出目标亮数 = 240  # 最后一层平均每帧亮几个（0 = 关闭归一化，退回固定阈值旧版）
校准帧数 = 8        # 出生校准用几帧随机输入（越大越稳，构建越慢一点）

大像素数 = 大像素行数 * 大像素列数
对数 = 大像素数 * 通道数 * 每档对数      # 输入层特征神经元对数
池 = 特征神经元池(对数)
网 = 神经网络(池, 层数=层数, 连接半径=连接半径,
             权重范围=权重范围, 阈值初值=阈值初值,
             输出感受野=输出感受野, 输出目标亮数=输出目标亮数,
             校准帧数=校准帧数)


def 蛇形像素(行, 列):
    """图像坐标 (行,列) -> 环上第几个大像素。奇数行反着走，
    保证图像里上下/左右相邻的大像素在环上也相邻。"""
    return 行 * 大像素列数 + (列 if 行 % 2 == 0 else 大像素列数 - 1 - 列)


def 降采样(图像):
    """任意 高x宽x3 图像 -> (大像素行数, 大像素列数, 3)，每格取块平均，数值 0~1"""
    h, w, _ = 图像.shape
    ys = (np.arange(大像素行数 + 1) * h) // 大像素行数
    xs = (np.arange(大像素列数 + 1) * w) // 大像素列数
    浮点 = 图像.astype(np.float64)
    和 = np.add.reduceat(浮点, ys[:-1], axis=0)
    和 = np.add.reduceat(和, xs[:-1], axis=1)
    行高 = (ys[1:] - ys[:-1])[:, None, None]
    列宽 = (xs[1:] - xs[:-1])[None, :, None]
    return 和 / (行高 * 列宽) / 255.0


def 图像转信号(图像):
    """任意 高x宽x3 图像 -> 池.信号（温度计码：每通道亮度 L = 前 L 对正激活）。

    亮度 0   = 该通道 k 对全部反神经元激活；
    亮度满   = 该通道 k 对全部正神经元激活；
    中间亮度 = 前 L 对正激活、后 k-L 对反激活（交界位置 = 亮度值）。
    """
    缩 = 降采样(图像)                                # (行,列,3) 0~1
    级 = np.clip(np.rint(缩 * 每档对数).astype(int), 0, 每档对数)

    信号 = np.zeros(池.总数)
    rr = np.arange(大像素行数)[:, None, None]
    cc = np.arange(大像素列数)[None, :, None]
    蛇列 = np.where(rr % 2 == 0, cc, 大像素列数 - 1 - cc)   # 蛇形像素列号
    像素对 = (rr * 大像素列数 + 蛇列) * (通道数 * 每档对数)  # 每个大像素的对起点
    ch = np.arange(通道数)[None, None, :]
    起点 = 像素对 + ch * 每档对数                        # 每个(行,列,通道)的对起点

    for j in range(每档对数):
        对 = 起点 + j
        正掩码 = 级 > j                    # 亮度超过第 j 档 -> 这一对正激活
        信号[(2 * 对)[正掩码]] = 1.0
        信号[(2 * 对 + 1)[~正掩码]] = 1.0
    return 信号


def 解码亮度(激活=None):
    """从输入层激活状态读回每个大像素的 R/G/B 亮度（0~每档对数），用来检查编码"""
    if 激活 is None:
        激活 = 池.激活
    亮度 = np.zeros((大像素行数, 大像素列数, 通道数), dtype=int)
    for r in range(大像素行数):
        for c in range(大像素列数):
            起 = 蛇形像素(r, c) * 通道数 * 每档对数
            段 = 激活[2 * 起: 2 * (起 + 通道数 * 每档对数): 2]   # 每对的正神经元
            亮度[r, c] = 段.reshape(通道数, 每档对数).sum(axis=1)
    return 亮度


def 造测试图(模式, 帧=0, 宽=1920, 高=1080):
    """合成测试画面：模拟 1920x1080 高清帧，看降采样成马赛克后对不对"""
    图 = np.zeros((高, 宽, 3), dtype=np.uint8)
    if 模式 == "渐变":
        ramp = np.linspace(0, 255, 宽)
        图[:] = ramp[None, :, None]                    # 灰阶横向渐变
    elif 模式 == "色块":
        图[:高 // 2, :宽 // 2] = (255, 0, 0)            # 左上红
        图[:高 // 2, 宽 // 2:] = (0, 255, 0)            # 右上绿
        图[高 // 2:, :宽 // 2] = (0, 0, 255)            # 左下蓝
        图[高 // 2:, 宽 // 2:] = (255, 255, 255)        # 右下白
    elif 模式 == "移动条":
        x = (帧 * (宽 // 12)) % 宽
        图[:, x: x + 宽 // 16] = 255                    # 白色竖条一帧帧移动
    return 图


